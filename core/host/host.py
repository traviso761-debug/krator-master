#!/usr/bin/env python3
"""The host shell's file list (core/host/README.md; ROADMAP.md section 10). A build.py takes the shell the way it takes
core/biome: it names the files it wants (SHELL is the set every build on the shell takes) and resolves them, a local src/
copy with the same name winning for that build (record the override in that build's KNOWN_ISSUES.md):

    sys.path.insert(0, os.path.join(ROOT, 'core', 'host'))
    import host as khost
    CORE_HOST = khost.SHELL
    khost.resolve(PATH, CORE_HOST)          # PATH: {fragment name: path}; adds the ones the build does not have

The world clock is core/clock's (91-host-loop.js owns a KCLOCK), so it is in the list too."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.dirname(HERE)
# fragment name -> the core folder it lives in
WHERE = {
    '20-core-clock.js': 'clock',
    '90-host-camera.js': 'host',
    '91-host-loop.js': 'host',
    '92-host-panel.js': 'host',
    '94-host-polytool.js': 'host',   # opt-in: the authoring tools (inspect, polygon, path)
    '95-host-probe.js': 'host',
    '93-host-inspect.js': 'host',     # the record-driven inspector
    '93-host-stocks.js': 'host',      # what things hold and the settlement's stocks (o.holds; Voth's 56e, the standard)
    '94-host-marks.js': 'host',       # marks: areas, lines, points, measured (supersede the polytool)
    '96-host-pictures.js': 'host',    # the picture menu (o.palette)
    '97-host-minimap.js': 'host',     # the minimap from the records (needs core/minimap's 88 and 88a)
    '98-host-edit.js': 'host',        # edit modes: core/edits operations (needs core/edits)
    '99-host-cutaway.js': 'host',     # the cutaway and its storey bar (o.cutaway)
    '40-core-edits.js': 'edits',
    '20-core-space.js': 'space',
    '88-core-minimap.js': 'minimap',
    '88a-core-minimap-host.js': 'minimap',
}
SHELL = ['20-core-clock.js', '90-host-camera.js', '91-host-loop.js', '92-host-panel.js', '95-host-probe.js']
# the whole interface (ROADMAP.md section 10, step 2 on): the shell, the inspector, marks, pictures, minimap, editor, cutaway,
# and the core modules they read (core/edits, core/space, core/minimap)
FULL = SHELL + ['93-host-inspect.js', '93-host-stocks.js', '94-host-marks.js', '96-host-pictures.js', '97-host-minimap.js', '98-host-edit.js',
                '99-host-cutaway.js', '40-core-edits.js', '20-core-space.js', '88-core-minimap.js', '88a-core-minimap-host.js']
EDITS_JS = '39-host-edits.js'      # the generated fragment edits_js() writes (sorts before core/edits and every builder)


def path(name):
    return os.path.join(CORE, WHERE[name], name)


def resolve(paths, names=SHELL):
    """Add each named shell file to `paths` unless the build has its own copy of that name. Returns the overrides."""
    own = []
    for f in names:
        if f in paths:
            own.append(f)
        else:
            paths[f] = path(f)
    return own


def edits_js(build_dir, build):
    """The page's edits (ROADMAP.md section 10, "host.py inlines a build's edits"): <build_dir>/edits.json, written by the
    editor's Save through tools/edits/serve.py, as `var KHOST_EDITS`; a newer draft in this browser (the editor keeps one
    on every change, localStorage 'khost-edits:<build>') wins over it, so an unsaved edit survives a reload. The build
    applies KHOST_EDITS as it makes the world. No file: the page reads only the draft (null without one)."""
    import json
    f = os.path.join(build_dir, 'edits.json')
    log = None
    if os.path.isfile(f):
        with open(f, encoding='utf-8') as fh:
            log = json.load(fh)
        if log.get('format') != 'krator-edits':
            raise SystemExit('%s: not a krator-edits log' % f)
    return ('/* ' + EDITS_JS + ': GENERATED by core/host/host.py edits_js() from ' + build + '/edits.json; do not edit */\n'
            'var KHOST_EDITS_SRC = null;\n'
            'var KHOST_EDITS = (function(){ var f = ' + json.dumps(log, separators=(',', ':'), sort_keys=True) + ';\n'
            ' try { var d = localStorage.getItem(' + json.dumps('khost-edits:' + build) + ');\n'
            '   if (d) { d = JSON.parse(d); if (d && d.format === "krator-edits" && (!f || (d.saved || "") > (f.saved || ""))) { KHOST_EDITS_SRC = "draft"; return d; } } } catch (e) {}\n'
            ' if (f) KHOST_EDITS_SRC = "file";\n'
            ' return f; })();\n')
