// ================================================================= CORE — audio catalogue: licenses, clip records, filters, credits
// The data side of core/audio (core/audio/PLAN.md sections 1-3). Plain records and pure functions: no Web Audio, no DOM,
// no three.js, so the lab, the tools and Godot read the same rules. The policy itself is data (data/licenses.json):
// this file only applies it. One shared object, KAUDIO.
//
//   KAUDIO.useLicenses(table)          table = data/licenses.json ({order, licenses}); returns KAUDIO
//   KAUDIO.licenseOf(text)             a source's own license text -> license id ('unverified' when nothing matches)
//   KAUDIO.license(id)                 the license record, or the 'unverified' one
//   KAUDIO.inGame(id) / shareable(id) / creditRequired(id)
//   KAUDIO.check(rec, catalog)         an intake record's problems, [] when it may enter the catalogue (catalog: clips by id)
//   KAUDIO.attribution(rec)            the credit line: "Title" by Creator, source page, license name
//   KAUDIO.filter(clips, q)            q: {text, category, kind, tags[], license, status, share, minDur, maxDur}
//   KAUDIO.sort(clips, key, desc)      key: title | creator | duration | category | license | id
//   KAUDIO.credits(clips, title)       CREDITS markdown: required credits first, courtesy credits after
(function(root){
  var L=null;
  function useLicenses(t){L=t;return api;}
  function need(){if(!L)throw new Error('KAUDIO: call useLicenses(data/licenses.json) first');return L;}
  function license(id){var T=need();return T.licenses[id]||T.licenses.unverified;}
  function licenseOf(text){
    var T=need(),s=String(text==null?'':text);
    if(!s)return 'unverified';
    for(var i=0;i<T.order.length;i++){var id=T.order[i],m=T.licenses[id].match||[];
      for(var j=0;j<m.length;j++)if(s.indexOf(m[j])>=0)return id;}
    return 'unverified';
  }
  function inGame(id){return !!license(id).game;}
  function shareable(id){return !!license(id).share;}
  function creditRequired(id){return license(id).credit==='required';}

  var ID=/^[a-z0-9][a-z0-9._-]{1,79}$/;
  function check(rec,catalog){
    var p=[];rec=rec||{};catalog=catalog||{};
    if(!ID.test(rec.id||''))p.push('id: lower-case letters, digits, dot, dash or underscore, 2 to 80 long');
    else if(catalog[rec.id])p.push('id: already in the catalogue');
    if(!rec.title)p.push('title: missing');
    if(!rec.creator)p.push('creator: missing (the recordist, not the uploader of a compilation)');
    if(!/^https?:\/\//.test(rec.source||''))p.push('source: the item\'s own page is missing');
    var T=need();
    if(!T.licenses[rec.license])p.push('license: "'+rec.license+'" is not an id in data/licenses.json');
    else if(!inGame(rec.license))p.push('license: '+rec.license+' is not allowed ('+(license(rec.license).why||'policy')+')');
    else if(creditRequired(rec.license)&&!rec.attribution)p.push('attribution: this license requires a credit line');
    if(!rec.category)p.push('category: missing');
    if(!(rec.duration>0))p.push('duration: missing');
    return p;
  }
  function attribution(rec){
    var l=license(rec.license);
    return '"'+rec.title+'" by '+(rec.creator||'unknown')+(rec.source?', '+rec.source:'')+', '+l.name+(l.url?' ('+l.url+')':'');
  }
  function lc(s){return String(s==null?'':s).toLowerCase();}
  function filter(clips,q){
    q=q||{};var words=lc(q.text).split(/\s+/).filter(Boolean),tags=q.tags||[];
    return clips.filter(function(c){
      if(q.category&&c.category!==q.category)return false;
      if(q.kind&&String(c.category).split('.')[0]!==q.kind&&!(q.kind==='bed'&&c.category==='amb.bed'))return false;
      if(q.license&&c.license!==q.license)return false;
      if(q.status&&c.status!==q.status)return false;
      if(q.share!=null&&!!c.share!==!!q.share)return false;
      if(q.minDur!=null&&!(c.duration>=q.minDur))return false;
      if(q.maxDur!=null&&!(c.duration<=q.maxDur))return false;
      var ct=c.tags||[];for(var i=0;i<tags.length;i++)if(ct.indexOf(tags[i])<0)return false;
      if(words.length){var hay=lc([c.id,c.title,c.creator,c.notes,ct.join(' '),c.category].join(' '));
        for(var w=0;w<words.length;w++)if(hay.indexOf(words[w])<0)return false;}
      return true;
    });
  }
  function sort(clips,key,desc){
    var k=key||'title',out=clips.slice();
    out.sort(function(a,b){var x=a[k],y=b[k],r;
      if(typeof x==='number'||typeof y==='number')r=(+x||0)-(+y||0);else r=lc(x)<lc(y)?-1:lc(x)>lc(y)?1:0;
      if(!r)r=a.id<b.id?-1:a.id>b.id?1:0;return desc?-r:r;});
    return out;
  }
  function credits(clips,title){
    var req=[],cour=[];
    sort(clips,'creator').forEach(function(c){if(!inGame(c.license))return;(creditRequired(c.license)?req:cour).push('- '+(c.attribution||attribution(c)));});
    var out=['# '+(title||'Sound credits'),'','Generated by core/audio/tools/catalog.js from core/audio/data/clips.json. Do not edit by hand.',''];
    if(req.length)out.push('## Required by the license','',req.join('\n'),'');
    if(cour.length)out.push('## With thanks (public domain, CC0 and royalty-free: credit not required)','',cour.join('\n'),'');
    return out.join('\n');
  }
  var api={useLicenses:useLicenses,licenseOf:licenseOf,license:license,inGame:inGame,shareable:shareable,creditRequired:creditRequired,
    check:check,attribution:attribution,filter:filter,sort:sort,credits:credits};
  root.KAUDIO=api;
})(typeof window!=='undefined'?window:globalThis);
