/* ============================== 16Y. FURNITURE — placed from the catalog (FURNISH) ==============================
   Everything a kit building (64-locus-*, 65-abyss-*) puts in or around itself that is not its structure or an
   outbuilding is FURNITURE: a master-catalog piece (kits/catalog), placed as DATA on the building and built by the
   catalog's own code through KratorFurniture (65z, generated by build.py from kits/catalog/furniture_bundle.py),
   merged into one mesh per render family for the whole page. A builder calls, in its own local frame:
     FURNISH(key, lx, ly, lz, lry, { v, seed, setting, lamp })   -> the placement record
   (ABYSS.furn(F, key, lx,lz, yaw, opt) is the Abyss kit's own spelling of the same call). The record (core/furnish)
   { id, key, variant, seed, lx, ly, lz, lry, x, y, z, ry, building, part, setting, room, job } goes on the frame (F.furniture)
   and on the building's record (buildAsset(...).furniture). The catalog origin is the piece's FOOTPRINT CENTRE.
   setting: 'outdoor' (default) | 'indoor' (inside, in a space the interior set plans no room for) |
            'room' (stands in an OPEN room the interior set plans — a stall, a sail court, a tavern deck: placed only
            while the interiors do not furnish that building, so ?interiors=1 never doubles it).
   Lights the pieces carry (catalog F.lamp, kept as data) become this engine's night lamps (nlLampAdd); lamp:[amp,rad]
   overrides their strength. Indoors, the rooms of every TOP-LEVEL building are the interiors kit's: its sets
   (kits/interiors/sets/locus.js, abyss.js) are planned and furnished through the same catalog with ?interiors=1 (off by
   default: roofs hide it and it adds triangles). The item is `<key>` for variant 0 and `<key>#<variant>` for any other:
   a variant with no item of its own is NOT furnished (never variant 0's rooms on another body), and is counted in
   LOCF.unfurnished.noItem. ?furniture=0 places
   nothing (the records are still kept). A key the catalog lacks is counted in LOCF.missing, never thrown. */
KratorFurniture.setDetail(.5);   /* settlement-scale: half the segments on round furniture parts */
/* the placement pass is core/furnish (50-core-furnish.js: the record, the missing count, the id); this is Locus's adapter
   onto it: its seed rule (the frame's seed and the spot in it), the open rooms the interiors take over, the night lamps
   and the inspector entry */
regFlush();   /* the sites registered before core/tags' vocabulary loaded (45-kit.js REGISTER) */
/* ---------------------------------------------------------------- the owner's edits, as the page is made (as Girder's 53-furnish.js)
   KHOST_EDITS (39-host-edits.js, written by core/host/host.py from edits.json or this browser's draft) is a core/edits log;
   the world page only (a kit sheet has no log). A piece merged into the batch cannot be taken out of it afterwards, so a
   piece the log moves or removes is not drawn at all (its record stays, for the log to find); 98-start.js applies the log:
   the moved piece is drawn on its own where it went, an added one likewise. A target is its core/tags uid, else its key
   within 1.5 m (core/edits/README.md). */
var LEDIT = { log: (!SHEET && typeof KHOST_EDITS !== 'undefined' && KHOST_EDITS && KHOST_EDITS.ops) ? KHOST_EDITS : null, vetoed: [] };
LEDIT.hits = LEDIT.log ? LEDIT.log.ops.filter(function(op){ return (op.op==='REMOVE' || op.op==='MOVE') && op.target && (op.target['class']==='furniture' || op.target['class']==='flora'); }) : [];
function locfVetoed(r){
  if(!LEDIT.hits.length || !r) return false;
  for(var i=0;i<LEDIT.hits.length;i++){ var t=LEDIT.hits[i].target;
    if(t.uid != null){ if(t.uid === r.uid) return true; }
    else if(t.at && t.key === r.key && Math.hypot(t.at[0]-r.at[0], t.at[2]-r.at[2]) < 1.5 && Math.abs((t.at[1]||0)-r.at[1]) < 1.5) return true; }
  return false;
}
var LOCF = KFURN.create(Object.assign(KFURN.flags(false), {
  catalog: KFURN.catalogOf(KratorFurniture), interiors: KratorInteriors, walk: KWALK,
  tags: (KTAGS.page = KTAGS.page || KTAGS.create({ build:'locus' })),   /* every piece registered in core/tags (core/tags/README.md); the sites are already there (45-kit.js REGISTER) */
  seed: function(o, ctx, R, x, y, z, loc){ return (((ctx.frame.seed||1)*37+Math.round(loc[0]*11+loc[2]*17)+997)&0xffff); },
  onRecord: function(rec, ctx){
    if(rec.setting==='room' && LOCF.interiors && LOCF.item(ctx.building, ctx.top.variant|0)){ rec.deferred='interiors'; LOCF.deferred++; return false; } },
  draw: function(rec, ctx, o, A){
    if(locfVetoed(KTAGS.page.get(rec.id))){ LEDIT.vetoed.push(rec.id); return; }   /* the owner's edits: moved or removed (98-start.js) */
    var r=KFURN.drawRec(LOCF, rec, ctx.frame.wealth);
    if(r.error) ERR('furniture '+rec.key+': '+r.error);
    r.lights.forEach(function(l){ nlLampAdd(l.x, l.y, l.z, o.lamp?o.lamp[0]:l.intensity, o.lamp?o.lamp[1]:l.distance, false); });
    var dm=KratorFurniture.entryDims(A, rec.variant)||A;
    REGISTER({ name:A.name+(A.variantNames?' — '+A.variantNames[rec.variant%A.variantNames.length]:''), kind:'furniture',
      label:'furniture · catalog · culture: '+A.culture+' · '+(A.type||'')+' · '+rec.setting+' · '+dm.w+' x '+dm.d+' m · key '+rec.key,
      x:rec.x, y:rec.y-0.2, z:rec.z, r:Math.hypot(dm.w,dm.d)/2+0.4, h:(dm.h||2)+0.6, tid:rec.id }); }   /* tid: its core/tags record (45-kit.js) */
}));
Object.assign(LOCF, { stack:[], lastTop:null, deferred:0, unfurnished:{ noItem:{}, skip:{}, none:{} } });
KFURN.useBatch(LOCF, KratorFurniture, KratorInteriors, { indexed: true });   /* indexed meshes (kits/catalog/README.md) */
window._locf = LOCF;
/* every interior piece (?interiors=1) is a core/tags record too (its building as parent), so the inspector names it and the
   owner's edits can move or remove it (a vetoed piece is not built), as Girder's 56-interiors.js */
LOCF.ixN = 0;
if(LOCF.adapter) (function(){
  var build0 = LOCF.adapter.build;
  LOCF.adapter.build = function(p, room){
    var E = KratorFurniture.FURN_BY_KEY[p.key] || {}, t = { setting:'room' };
    if(E.culture) t.culture = E.culture; if(E.tier) t.tier = E.tier; if(room && room.id != null) t.room = String(room.id);
    var r = KTAGS.page.add({ id:'ixf_'+('0000'+(++LOCF.ixN)).slice(-5), 'class':'furniture', kind:E.type||null, key:p.key, name:E.name||null,   /* its own ids: core/furnish passes furn_<n> later */
      parent: room && room.building != null ? String(room.building) : null, at:[p.x, p.y||0, p.z], ry:p.ry||0,
      size: E.w ? [E.w, E.d, E.h] : undefined, tags:t, frag:'66-locus-furnish.js (interiors)' });
    if(locfVetoed(r)){ LEDIT.vetoed.push(r.id); return { key:p.key, variant:p.variant, seed:p.seed, x:p.x, y:p.y, z:p.z, ry:p.ry, building:room?room.building:null, room:room?room.id:null, setting:'indoor', lights:[] }; }
    return build0.call(this, p, room);
  };
})();   /* for probes: the records, LOCF.missing, LOCF.buildings */
/* the interior-set item that furnishes a building of this key and variant (null: none, or skipped). Variant 0 is `<key>`,
   variant n `<key>#n` ONLY: no fallback to `<key>`, whose rooms are measured on variant 0's body */
LOCF.itemOf = function(key, v){ return KratorInteriors.sets.find(v ? key+'#'+v : key); };
LOCF.item = function(key, v){ var it=LOCF.itemOf(key, v); return it && !it.skip ? it : null; };
/* why a top-level building gets no interior: 'skip' (its item says so, or the base item of a key skipped as a whole: an open
   shade, a jetty, a prop), 'noItem' (a variant > 0 of a key whose base item plans rooms, with no item of its own: a gap
   in the set), 'none' (the key has no item at all) */
LOCF.why = function(key, v){ var it=LOCF.itemOf(key, v), base=v?KratorInteriors.sets.find(key):null;
  return it ? 'skip' : (base ? (base.skip ? 'skip' : 'noItem') : 'none'); };
/* place a catalog piece at (lx,ly,lz) in frame F (the catalog origin: the footprint centre), turned lry */
function furnishAt(F, key, lx,ly,lz, lry, o){ o=o||{};
  var F0=LOCF.stack[0]||F, top=F0.asset?F0.asset.key:'', q=F.p(lx,lz);
  return LOCF.place(key, q[0], F.y+ly, q[1], F.ry+(lry||0), o, [lx, ly, lz, lry||0],
    { building:top, part:F.asset&&F.asset.key!==top?F.asset.key:null, frame:F, top:F0, listOf:function(){ return F0.furniture||(F0.furniture=[]); } }); }
/* the builder's call: its own (innermost) frame is the one on top of the stack */
function FURNISH(key, lx,ly,lz, lry, o){ var F=LOCF.stack[LOCF.stack.length-1];
  if(!F){ ERR('FURNISH '+key+' outside a builder'); return null; } return furnishAt(F, key, lx,ly,lz, lry, o); }
/* every ASSET's build runs with its frame on the stack (sub-assets built by ABYSS.sub / LOCUS.sub too) */
ASSETS.forEach(function(A){ var b=A.build; A.build=function(F){ if(!LOCF.stack.length) LOCF.lastTop=F; LOCF.stack.push(F);
  try{ return b.call(this, F); } finally{ LOCF.stack.pop(); } }; });
/* the building's record carries its furniture; a TOP-LEVEL placement with an interior-set item gets its rooms planned and
   furnished there with ?interiors=1 (the plan summary is data on the record: rec.interior) */
var locfBuildAsset = buildAsset;
buildAsset = function(key, x,z,ry, opt){ var top=!LOCF.stack.length; LOCF.lastTop=null;
  var rec=locfBuildAsset(key, x,z,ry, opt), F=LOCF.lastTop; if(!rec || !top) return rec;
  rec.furniture = (F && F.furniture) || [];
  if(LOCF.interiors && F){ var it=LOCF.item(key, F.variant|0);
    if(it){ var fi=LOCF.interior(it, x, z, ry||0, LOCF.adapter, { baseY:F.y, prefix:'lc.'+LOCF.buildings.length+'.' }), r=fi.result;
      rec.interior=fi.summary;
      r.inst.rooms.forEach(function(R){ var P=r.plans[R.id]; (P&&P.lights||[]).forEach(function(l){ nlLampAdd(l.x, l.y, l.z, l.intensity||0.7, l.distance||10, false); }); });
      Object.assign(LOCF.buildings[LOCF.buildings.length-1], { key:key, variant:F.variant|0 }); }
    else { var w=LOCF.why(key, F.variant|0), u=LOCF.unfurnished[w], k=key+((F.variant|0)?'#'+(F.variant|0):''); u[k]=(u[k]||0)+1; } }
  return rec; };
/* the batch becomes meshes once, when the kit emits its instances (75-terrain.js); they take the night-glow hook */
var locfEmit = emitBuckets;
/* the batch's vertex colours are the catalog's sRGB bytes; this renderer outputs sRGB from LINEAR colours (the kit converts
   its own instance colours), so they are converted here, through a 256-entry table, into a float attribute */
var LOCF_LIN = KFURN.SRGB_LIN;
emitBuckets = function(){ var g=LOCF.batch.flush(scene); g.traverse(function(m){ if(!m.isMesh) return;
    var c=m.geometry.attributes.color; if(c){ var a=c.array, f=new Float32Array(a.length); for(var i=0;i<a.length;i++) f[i]=LOCF_LIN[a[i]]; m.geometry.setAttribute('color', new THREE.BufferAttribute(f, 3)); }
    if(!m.material.isMeshBasicMaterial) nlMaterial(m.material, 'kf-'+m.material.userData.family); });
  LOCF.group=g; window._furniture={ placed:LOCF.placed.length, deferred:LOCF.deferred, missing:LOCF.missing, meshes:g.children.length,
    tris:Math.round(LOCF.batch.tris), interiors:LOCF.buildings.length,
    noItem:Object.keys(LOCF.unfurnished.noItem).reduce(function(a,k){ return a+LOCF.unfurnished.noItem[k]; },0) };
  return locfEmit(); };
