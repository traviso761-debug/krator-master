/* ============================== 16Y. FURNITURE — placed from the catalog (FURNISH) ==============================
   Everything a kit building (64-locus-*, 65-abyss-*) puts in or around itself that is not its structure or an
   outbuilding is FURNITURE: a master-catalog piece (kits/catalog), placed as DATA on the building and built by the
   catalog's own code through KratorFurniture (65z, generated by build.py from kits/catalog/furniture_bundle.py),
   merged into one mesh per render family for the whole page. A builder calls, in its own local frame:
     FURNISH(key, lx, ly, lz, lry, { v, seed, setting, lamp })   -> the placement record
   (ABYSS.furn(F, key, lx,lz, yaw, opt) is the Abyss kit's own spelling of the same call). The record
   { key, variant, seed, lx, ly, lz, lry, x, y, z, ry, building, part, setting } goes on the frame (F.furniture)
   and on the building's record (buildAsset(...).furniture). The catalog origin is the piece's FOOTPRINT CENTRE.
   setting: 'outdoor' (default) | 'indoor' (inside, in a space the interior set plans no room for) |
            'room' (stands in an OPEN room the interior set plans — a stall, a sail court, a tavern deck: placed only
            while the interiors do not furnish that building, so ?interiors=1 never doubles it).
   Lights the pieces carry (catalog F.lamp, kept as data) become this engine's night lamps (nlLampAdd); lamp:[amp,rad]
   overrides their strength. Indoors, the rooms of every TOP-LEVEL building are the interiors kit's: its sets
   (kits/interiors/sets/locus.js, abyss.js; item `<key>#<variant>`, else `<key>`) are planned and furnished through
   the same catalog with ?interiors=1 (off by default: roofs hide it and it adds triangles). ?furniture=0 places
   nothing (the records are still kept). A key the catalog lacks is counted in LOCF.missing, never thrown. */
KratorFurniture.setDetail(.5);   /* settlement-scale: half the segments on round furniture parts */
var LOCF = { on:!/[?&]furniture=0\b/.test(location.search), interiors:/[?&]interiors=1\b/.test(location.search),
  batch:KratorFurniture.batch(), placed:[], missing:{}, buildings:[], stack:[], lastTop:null, deferred:0, group:null };
LOCF.adapter = KratorInteriors.runtimeAdapter(KratorFurniture, LOCF.batch);
window._locf = LOCF;   /* for probes: the records, LOCF.missing, LOCF.buildings */
/* the interior-set item that furnishes a building of this key and variant (null: none, or skipped) */
LOCF.item = function(key, v){ var S=KratorInteriors.sets, it=(v?S.find(key+'#'+v):null)||S.find(key); return it && !it.skip ? it : null; };
/* place a catalog piece at (lx,ly,lz) in frame F (the catalog origin: the footprint centre), turned lry */
function furnishAt(F, key, lx,ly,lz, lry, o){ o=o||{};
  var F0=LOCF.stack[0]||F, top=F0.asset?F0.asset.key:'', setting=o.setting||'outdoor';
  if(!KratorFurniture.has(key)){ LOCF.missing[key]=(LOCF.missing[key]||0)+1; return null; }
  var q=F.p(lx,lz), rec={ key:key, variant:o.v|0, seed:o.seed||(((F.seed||1)*37+Math.round(lx*11+lz*17)+997)&0xffff),
    lx:lx, ly:ly, lz:lz, lry:lry||0, x:q[0], y:F.y+ly, z:q[1], ry:F.ry+(lry||0), building:top, part:F.asset&&F.asset.key!==top?F.asset.key:null, setting:setting };
  (F0.furniture||(F0.furniture=[])).push(rec); LOCF.placed.push(rec);
  if(setting==='room' && LOCF.interiors && LOCF.item(top, F0.variant|0)){ rec.deferred='interiors'; LOCF.deferred++; return rec; }
  if(!LOCF.on) return rec;
  var r=LOCF.batch.place(key, rec.x, rec.y, rec.z, rec.ry, { variant:rec.variant, seed:rec.seed, wealth:F.wealth, building:top, setting:setting });
  if(r.error) ERR('furniture '+key+': '+r.error);
  r.lights.forEach(function(l){ nlLampAdd(l.x, l.y, l.z, o.lamp?o.lamp[0]:l.intensity, o.lamp?o.lamp[1]:l.distance, false); });
  var A=KratorFurniture.FURN_BY_KEY[key], dm=KratorFurniture.entryDims(A, rec.variant)||A;
  REGISTER({ name:A.name+(A.variantNames?' — '+A.variantNames[rec.variant%A.variantNames.length]:''), kind:'furniture',
    label:'furniture · catalog · culture: '+A.culture+' · '+(A.type||'')+' · '+setting+' · '+dm.w+' x '+dm.d+' m · key '+key,
    x:rec.x, y:rec.y-0.2, z:rec.z, r:Math.hypot(dm.w,dm.d)/2+0.4, h:(dm.h||2)+0.6 });
  return rec; }
/* the builder's call: its own (innermost) frame is the one on top of the stack */
function FURNISH(key, lx,ly,lz, lry, o){ var F=LOCF.stack[LOCF.stack.length-1];
  if(!F){ ERR('FURNISH '+key+' outside a builder'); return null; } return furnishAt(F, key, lx,ly,lz, lry, o); }
/* every ASSET's build runs with its frame on the stack (sub-assets built by ABYSS.sub / LOCUS.sub too) */
ASSETS.forEach(function(A){ var b=A.build; A.build=function(F){ if(!LOCF.stack.length) LOCF.lastTop=F; LOCF.stack.push(F);
  try{ return b.call(this, F); } finally{ LOCF.stack.pop(); } }; });
/* the building's record carries its furniture; a TOP-LEVEL placement with an interior-set item gets its rooms planned and
   furnished there with ?interiors=1 (the plan summary is data on the record: rec.interior) */
var locfBuildAsset = buildAsset;
buildAsset = function(key, x,z,ry, opt){ var top=!LOCF.stack.length; LOCF.lastTop=null;
  var rec=locfBuildAsset(key, x,z,ry, opt), F=LOCF.lastTop; if(!rec || !top) return rec;
  rec.furniture = (F && F.furniture) || [];
  if(LOCF.interiors && F){ var it=LOCF.item(key, F.variant|0);
    if(it){ var r=KratorInteriors.sets.furnish(it, x, z, ry||0, LOCF.adapter, { baseY:F.y, prefix:'lc.'+LOCF.buildings.length+'.' });
      rec.interior={ item:it.key, rooms:r.inst.rooms.length, pieces:Object.keys(r.plans).reduce(function(a,k){ return a+r.plans[k].placements.length; },0), residence:r.residence };
      r.inst.rooms.forEach(function(R){ var P=r.plans[R.id]; (P&&P.lights||[]).forEach(function(l){ nlLampAdd(l.x, l.y, l.z, l.intensity||0.7, l.distance||10, false); }); });
      LOCF.buildings.push({ key:key, variant:F.variant|0, x:x, z:z, ry:ry||0, interior:rec.interior }); } }
  return rec; };
/* the batch becomes meshes once, when the kit emits its instances (75-terrain.js); they take the night-glow hook */
var locfEmit = emitBuckets;
emitBuckets = function(){ var g=LOCF.batch.flush(scene); g.traverse(function(m){ if(m.isMesh && !m.material.isMeshBasicMaterial) nlMaterial(m.material, 'kf-'+m.material.userData.family); });
  LOCF.group=g; window._furniture={ placed:LOCF.placed.length, deferred:LOCF.deferred, missing:LOCF.missing, meshes:g.children.length,
    tris:Math.round(LOCF.batch.tris), interiors:LOCF.buildings.length };
  return locfEmit(); };
