// node settlements/gihon/bake_landing.js [--check] — the Landing's records for the open world (G3 on the region's ground)
// GH_LANDING.make (src/43-gh-landing.js: two core/city instances, a bank each, and a stone pier either side of the outlet) run
// with the Xanadu kit's boxes (test-gh-load.js: src and the opt-in extra/), written as plain records a region lays as a
// village of its own (core/world/48s-world-sites.js, a hamlet's `laid`): openworld/xanadu-oidong-highrift/src/
// 47g-site-gihon-landing.js. The frame is the Landing's (metres east and south of its mouth, scale model px GH_LANDING.PX); the
// region puts it on its own ground. --check makes it again and fails when the written file differs (a stale bake).
'use strict';
const fs=require('fs'),path=require('path');
const L=require('./test-gh-load.js');
const OUT=path.join(L.ROOT,'openworld','xanadu-oidong-highrift','src','47g-site-gihon-landing.js');
const r2=v=>Math.round(v*100)/100,r4=v=>Math.round(v*1e4)/1e4;
const X=GH_LANDING.make({dims:L.dims}),H=k=>{const D=L.dims(k,0);return D?D.h:8;};
const HOUSE={poor:1,middle:1,rich:1,manor:1};
/* the lots: the banks' buildings, each its footprint (the kit's fw x fd, what the region stands on its footing; core/city lays
   the Landing's lots on their boxes on a 2.5 m raster, so two on a bend may cross by a few decimetres at a corner of the box) */
const B=k=>L.DIMS[k]||{fw:8,fd:8};
const recs=X.lots.map(r=>({id:r.id,key:r.key,v:r.v|0,kind:r.civic?'civic':HOUSE[r.cls]?'house':'work',role:r.cls,
 x:r2(r.x),z:r2(r.z),ry:r4(r.ry),w:r2(B(r.key).fw),d:r2(B(r.key).fd),h:r2(H(r.key)),people:r.people}));
/* on the water: the piers' runs (the kit's mole, stretched to its run: len), the lighthouses on their heads, the barges at their
   berths and the ferry; `on: 'water'` with the deck's height over the lake (the region seats them on its water, not its ground) */
for(const e of X.extra){const D=L.dims(e.key,e.v)||{w:8,d:8,h:4};const pier=e.kind==='pier';
 recs.push(Object.assign({id:e.id,key:e.key,v:e.v|0,kind:e.kind,role:e.kind,x:r2(e.x),z:r2(e.z),ry:r4(e.ry),w:r2(pier?e.len:D.w),d:r2(D.d),h:r2(D.h),
  on:'water',deck:e.y},pier?{len:r2(e.len)}:{}));}
/* the ways: the quay streets, the roads inland, the side streets (core/city's), as lanes; the portage road's inland end is the
   Landing's own road's start */
const lanes=X.ways.map(w=>({id:w.id,w:w.w,main:w.cls==='main'&&/portage/.test(w.tag||''),tag:w.tag,pts:w.pts.map(p=>[r2(p[0]),r2(p[1])])}));
const port=lanes.find(l=>l.main),end=port.pts[port.pts.length-1];
const laid={format:'krator-laid-village',version:1,from:'settlements/gihon/src/43-gh-landing.js',px:GH_LANDING.PX,
 frame:{u:X.frame.u.map(r4),v:X.frame.v.map(r4),river:X.frame.river,pier:X.frame.pier},
 census:{pop:X.census.people,households:recs.filter(r=>r.kind==='house').length,buildings:X.census.buildings,byBank:X.census.byBank},
 end:[r2(end[0]),r2(end[1])],piers:X.piers.map(p=>({id:p.id,bank:p.bank,a:p.a.map(r2),b:p.b.map(r2),w:p.w,deck:p.deck})),
 records:recs,lanes};
const line=o=>JSON.stringify(o);
const js='// ================================================================= XANADU, OIDONG AND THE HIGH RIFT — the Landing, laid on core/city (GENERATED)\n'+
 '// [G data] GENERATED by settlements/gihon/bake_landing.js from settlements/gihon/src/43-gh-landing.js (GH_LANDING.make, step G3): do\n'+
 '// not edit. The Landing at the Lower Xanadu Lake\'s outlet (the owner, 2026-11-22: "Keep at the outlet"): two core/city instances,\n'+
 '// a bank each, a stone pier into the lake either side of the mouth, the barges and the ferry; records in metres east (x) and\n'+
 '// south (z) of the mouth (scale model px '+GH_LANDING.PX.join(',')+'). src/48-world-site.js lays it as a village of Kirstabal\'s lake\n'+
 '// (core/world/48s-world-sites.js, a hamlet\'s `laid`).\n'+
 'var GH_LANDING_LAID={format:'+line(laid.format)+',version:1,from:'+line(laid.from)+',px:'+line(laid.px)+',\n frame:'+line(laid.frame)+',\n census:'+line(laid.census)+
 ',end:'+line(laid.end)+',\n piers:'+line(laid.piers)+',\n records:[\n'+recs.map(line).join(',\n')+'],\n lanes:[\n'+lanes.map(line).join(',\n')+']};\n';
if(process.argv.includes('--check')){const old=fs.existsSync(OUT)?fs.readFileSync(OUT,'utf8'):'';
 console.log((old===js?'fresh':'STALE')+': '+path.relative(L.ROOT,OUT).replace(/\\/g,'/'));process.exit(old===js?0:1);}
fs.writeFileSync(OUT,js);
console.log('wrote '+path.relative(L.ROOT,OUT).replace(/\\/g,'/')+': '+recs.length+' records ('+X.lots.length+' lots, '+X.extra.length+' on the water), '+lanes.length+' lanes, '+
 laid.census.pop+' people, '+(js.length>>10)+' KB');
