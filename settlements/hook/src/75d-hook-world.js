/* ============================== HOOK: THE GROUND FROM THE SCALE MODEL ([G data]) ============================== */
/* Hook stands on the Krator Scale Model's ground at 1:1, through the open world's own rule (core/terrain/40-core-land.js
   KLAND: Catmull-Rom on the 4 km cells, the style's detail, the channels carved, the escarpments made into cliffs), on
   the cut round Hook's pixel (settlements/hook/world: cut.py, region.json and the rasters; HOOK_WORLD_DATA is their
   inline copy, generated by build.py). The kit's frame (x along the coast, +z the sea) is laid on the model here:
   the origin at the 1:1 shoreline due seaward of Hook's pixel and the frame turned to the coast's bearing there, so
   the P0 waterfront (kit z ~ 0) stands on the shelf's edge with the sea before it. Heights are the kit's: sea level
   0, so natH = the model's ground less the Ring Sea's level. PORT.natH (71-port-terrain.js) takes it in place of the
   kit's own coast; hookGroundH (76-hook-ground.js) reads it through portNatH. No three.js, no DOM.
     HOOK_WORLD.L            the KLAND instance (world metres, x east, z south, the origin at Hook's pixel)
     HOOK_WORLD.SEA          the Ring Sea's level in the model (m)
     HOOK_WORLD.origin       the kit's origin in the model's metres, .ex/.ez its axes, .bearing the coast's bearing
     HOOK_WORLD.toWorld(x,z) / .toLocal(wx,wz)   the frame, both ways
     HOOK_WORLD.natH(x,z)    the kit's natural ground: the model's at 1:1, sea level 0
     HOOK_WORLD.modelH(x,z)  the same, as the model has it (not lowered to the kit's sea level)
     HOOK_WORLD.report       the numbers the README quotes (the shoreline's offset, the bearing, the ground behind) */
const HOOK_WORLD=(()=>{
 const D=HOOK_WORLD_DATA,M=D.meta,lo=M.heights.lo,hi=M.heights.hi;
 /* the rasters as the open world decodes them from its PNGs (98-world-start.js): the same arithmetic, so the same land */
 const d16=a=>Float32Array.from(a,q=>lo+q/65535*(hi-lo)),u8=a=>Uint8Array.from(a);
 const R={elev:d16(D.elev),wlev:Float32Array.from(D.wlev,(q,i)=>D.whas[i]?lo+q/65535*(hi-lo):lo),whas:u8(D.whas),wflag:u8(D.wflag),
  scarpL:d16(D.scarpL),scarpU:d16(D.scarpU),scarpW:Float32Array.from(D.scarpW),
  clim:u8(D.clim),rain:u8(D.rain),temp:u8(D.temp),biome:u8(D.biome),mask:u8(D.mask)};
 const L=KLAND.create(M,R);
 /* the sea: the level of the wet cells (the Ring Sea; the cut holds no other water) */
 let SEA=-1e9;for(let i=0;i<R.whas.length;i++)if(R.whas[i]&&R.wlev[i]>SEA)SEA=R.wlev[i];
 /* the ground the frame is laid on: the land without its fine terms (minWave SEARCH_WAVE leaves out the roughness,
    the gullies, the channels and the metre-scale noise), so the shoreline is the slope's, not a ripple's */
 const SEARCH_WAVE=400,STEP=50;
 const hs=(x,z)=>L.H(x,z,SEARCH_WAVE)-SEA;
 /* the shoreline on a line of constant x: march seaward (-z: the sea is Hook's north) from z0 to the first point under
    the sea, then bisect to a centimetre. null when the march finds no sea */
 function shore(x,z0,zEnd){let a=z0;if(hs(x,a)<0)return null;
  for(let z=a-STEP;z>=zEnd;z-=STEP){if(hs(x,z)<0){let b=z;for(let k=0;k<24;k++){const m=(a+b)/2;if(hs(x,m)<0)b=m;else a=m;}return (a+b)/2;}a=z;}
  return null;}
 const z0=shore(0,0,-40000);
 if(z0==null)throw new Error('HOOK_WORLD: no shoreline seaward of Hook\'s pixel within 40 km');
 /* the coast's bearing: the shoreline at five stations 750 m apart along x, a least-squares line through them */
 const st=[];for(const dx of [-1500,-750,0,750,1500]){const z=shore(dx,z0+6000,z0-6000);if(z!=null)st.push([dx,z]);}
 let sx=0,sz=0,sxx=0,sxz=0;for(const p of st){sx+=p[0];sz+=p[1];sxx+=p[0]*p[0];sxz+=p[0]*p[1];}
 const n=st.length,slope=(n*sxz-sx*sz)/(n*sxx-sx*sx||1),zc=(sz-slope*sx)/n;
 /* the tangent along the coast and the normal toward the sea (the side where the ground is lower) */
 let tx=1/Math.hypot(1,slope),tz=slope/Math.hypot(1,slope);
 let nx=tz,nz=-tx;if(hs(nx*800,zc+nz*800)>hs(-nx*800,zc-nz*800)){nx=-nx;nz=-nz;}
 /* the kit's axes: +z to the sea, +x along the coast on the kit's right-handed side */
 const ez=[nx,nz],ex=[nz,-nx],O=[0,zc];
 const toWorld=(x,z)=>[O[0]+x*ex[0]+z*ez[0],O[1]+x*ex[1]+z*ez[1]];
 const toLocal=(wx,wz)=>{const dx=wx-O[0],dz=wz-O[1];return [dx*ex[0]+dz*ex[1],dx*ez[0]+dz*ez[1]];};
 const modelH=(x,z)=>{const w=toWorld(x,z);return L.H(w[0],w[1],0);};
 const natH=(x,z)=>modelH(x,z)-SEA;
 /* the coast's bearing in degrees from east, positive turning south (the model's +z). With the sea to the north the
    frame is a half turn: the kit's +x (ex) runs west, so the kit's -x end, the Point, lies at the world's EAST end of
    the waterfront (README.md "The ground": the owner's call whether the run is reversed) */
 const bearing=Math.atan2(tz,tx)*180/Math.PI;
 const report={sea_m:SEA,shore_from_pixel_m:Math.round(-zc),coast_bearing_deg:+bearing.toFixed(1),stations:st.map(p=>[p[0],Math.round(p[1])]),
  pixel_over_sea_m:Math.round(L.H(0,0,SEARCH_WAVE)-SEA),ex:ex.map(v=>+v.toFixed(4)),ez:ez.map(v=>+v.toFixed(4)),
  behind_m:[300,760,1180,1250,2000,4000].map(d=>[d,Math.round(hs(O[0]-d*ez[0],O[1]-d*ez[1]))]),
  seaward_m:[250,500,1000,2000].map(d=>[d,Math.round(hs(O[0]+d*ez[0],O[1]+d*ez[1]))]),
  style:(()=>{const w=toWorld(0,-400),s=L.styleAt(w[0],w[1]);return {hills:+s.hills.toFixed(2),terr:+s.terr.toFixed(2),wallK:+s.wallK.toFixed(2)};})(),
  relief_m:Math.round(L.gridBil(L.REL,0,0)),scarp:L.SW?Math.max.apply(null,Array.from(L.SW)):0};
 return {L,SEA,origin:O,ex,ez,bearing,toWorld,toLocal,natH,modelH,report,SEARCH_WAVE};})();
/* the kit's terrain takes the model's ground in place of its own coast (71-port-terrain.js portNatH -> PORT.natH) */
PORT.natH=HOOK_WORLD.natH;
