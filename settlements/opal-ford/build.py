#!/usr/bin/env python3
"""Ōpal-Phōrḍ, the opal road's river town (PLAN.md, step OF1; settlements/xanadu/BUILD-PLAN.md, A11): the town on core/city,
on Xanadu's page, on its own ground until the Siqārp region is cut (step OF2).

The page is Xanadu's, as Phēr's and Qiblai's are: settlements/xanadu/build.py --kit takes this folder's kit.json and targets/,
with core/city sealed in one closure (KCITY: gen/69p-kcity-bundle.js, generated here at every build from core/city and core/space,
never edited by hand), as settlements/pher/build.py seals it. The town's people come from its tune record (XAN_TUNE.opalford:
gen/69m-of-tune.js, core/region/data/xan-tune.js as it is under a numbered name, as settlements/marches reads it). The
buildings are the Xanadu kit's (kits/xanadu, through the page, and its opt-in extra/ pieces through kit.json). The ground is
registered with core/drawn for the audits.

    python3 tools/build.py settlements/opal-ford            # dist/opal-ford.html: the town
    node settlements/opal-ford/tests/test-of-site.js         # the plan in node
    KRATOR_GL=gpu python3 settlements/opal-ford/verify.py settlements/opal-ford/dist/opal-ford.html --assert --views "Overview,The ford"
"""
import io, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import buildlib                                   # noqa: E402
buildlib.through_tools_build(__file__)            # item 25: build-inputs.json is always written
import build_sources as BSRC                      # noqa: E402  (--list-sources: tools/dep_graph.py)

# the core modules this page takes (through Xanadu's build, gen/ and kit.json "external"): core/rand, core/tags, core/host,
# core/door, core/atmos, core/city and core/space (the bundle), core/region (XAN_TUNE), core/drawn
CORE_TAKEN = ('core/rand', 'core/tags', 'core/host', 'core/door', 'core/atmos', 'core/city', 'core/space', 'core/region', 'core/drawn')

# core/city in one closure (settlements/pher/build.py's kcity_bundle): its globals stay inside, and so does core/space
CITY_JS = sorted(f for f in os.listdir(os.path.join(ROOT, 'core', 'city')) if f[:2].isdigit() and f.endswith('.js') and ('-host-' not in f or f == '53-city-host-multikit.js'))
CITY_JS.insert(CITY_JS.index('42-city-multikit.js'), '../kits/10-core-kits.js')   # with 53, the multi-kit host (Stage 8 D8): inert until called
SPACE = 'core/space/20-core-space.js'
TUNE = 'core/region/data/xan-tune.js'
GEN = os.path.join(HERE, 'gen')
# a core/biome fragment of buildlib.CORE_BIOME_MIN that Xanadu's page lacks (settlements/pher/build.py BIO_MIN, the same reason)
BIO_MIN = {'86-bio-31b-core-leafset.js': 'core/biome/31b-core-leafset.js'}


def rd(rel):
    with io.open(os.path.join(ROOT, *rel.split('/')), encoding='utf-8') as fh:
        return fh.read()


def kcity_bundle():
    body = '\n/* ---- %s ---- */\n%s\nvar KSPACE = window.KSPACE;\n' % (SPACE, rd(SPACE))
    for f in CITY_JS:
        body += '\n/* ---- core/city/%s ---- */\n%s\n' % (f, rd('core/city/' + f))
        if f == '10-city-core.js':
            body += 'globalThis.KCITY = KCITY;\n'
    return ('/* KCITY: core/city and core/space in one closure (settlements/opal-ford/build.py). GENERATED: edit core/city. */\n'
            'var KCITY = (function(window){\n' + body +
            '\nKCITY.lib = { SL: SL, plan: function () { return PLAN; }, KSPACE: KSPACE, Raster: Raster, OCC: OCC, obb: obb, obbCorners: obbCorners };\n'
            'return KCITY;\n})(Object.create(window));\n')


def write_gen():
    os.makedirs(GEN, exist_ok=True)
    outs = {'69p-kcity-bundle.js': kcity_bundle(),
            '69m-of-tune.js': ('// GENERATED by settlements/opal-ford/build.py at every build: %s as it is, under a numbered name so it loads\n'
                               '// before the town (targets/town/89zp-of-site.js reads XAN_TUNE.opalford). Edit the tune, never this. [G data]\n' % TUNE) + rd(TUNE)}
    for f, rel in BIO_MIN.items():
        outs[f] = '/* %s, read from core at every build (settlements/opal-ford/build.py BIO_MIN). GENERATED: edit core/biome. */\n%s' % (rel, rd(rel))
    for f, new in outs.items():
        out = os.path.join(GEN, f)
        old = io.open(out, encoding='utf-8').read() if os.path.exists(out) else None
        if old != new:
            with io.open(out, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write(new)


BSRC.note(*([SPACE, TUNE] + ['core/city/' + f for f in CITY_JS] + sorted(BIO_MIN.values())))
# the Xanadui script the Qiblai kit lifts from the chart (kits/qiblai/xanadui_script.py), current before its fragments are read
# (the Iridescent Order's house is the Qiblai kit's: kit.json externalDirs kits/qiblai/src, as settlements/lightwall takes it)
sys.path.insert(0, os.path.join(ROOT, 'kits', 'qiblai')); import xanadui_script
BSRC.note(xanadui_script.CHART, os.path.join(ROOT, 'kits', 'qiblai', 'xanadui_script.py'))
if not BSRC.LISTING:
    write_gen()
    xanadui_script.write()

if '--no-checks' not in sys.argv:
    if subprocess.call([sys.executable, os.path.join(ROOT, 'tools', 'check_port.py'), '--quiet', HERE]) != 0:
        sys.exit('build.py: the port lint failed (tools/check_port.py); fix the fragment or retag it in PORT.md')

_rc = subprocess.call([sys.executable, os.path.join(ROOT, 'settlements', 'xanadu', 'build.py'), '--kit', HERE] + sys.argv[1:],
                      cwd=os.path.join(ROOT, 'settlements', 'xanadu'))
if not _rc:
    BSRC.report()
sys.exit(_rc)
