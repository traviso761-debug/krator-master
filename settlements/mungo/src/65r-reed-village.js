/* ============================== 16R. THE REED VILLAGE — built by the Reed Lake kit ==============================
   The offshore district is drawn by the REED LAKE KIT itself (settlements/reedlake), not by a port of it: the
   kit's fragments run inside REEDKIT_MAKE (01-reedkit.html, generated by build.py, its own <script>, no shared
   global), fed the layout's records (30-layout.js: REED). Its InstancedMeshes and meshes hang under one group
   standing REED_Y above the water, so the kit's island top (y 0) is where the walk graph's reed decks are.
   Its registry goes to the inspector (REGISTER), its fires to the night-light volume (nlLampAdd) and its
   firelight items are switched with the night. Any def the kit does not have yet (Reed's Local, while it is
   being built) falls back and is listed in window._reed.missing.                                          */
var REEDKIT = null, REED_BUILT = null;
(function(){
  if(SHEET) return;
  var t0 = performance.now();
  try{ REEDKIT = REEDKIT_MAKE({ onerror:window.onerror, reedY:REED_Y, camera:camera,
      register:function(o){ REGISTER(o); }, lamp:function(x,y,z,a,r){ nlLampAdd(x,y,z,a,r,false); } }); }
  catch(e){ ERR('reed kit: '+(e&&e.stack||e)); return; }
  REED.reedBeds = REED_BEDS;   /* the marsh at the mouth (30-layout.js 7b), planted by the same kit */
  try{ REED_BUILT = REEDKIT.build(REED); scene.add(REED_BUILT.root); }
  catch(e){ ERR('reed village: '+(e&&e.stack||e)); return; }
  /* the inspector and the click-probe pick only the scene's own children (80-camera.js pickWorld), so every mesh the
     kit made is lifted out of its groups into the scene, keeping its world transform (Object3D.attach); unlabelled
     ones are named for the inspector */
  var reedMeshes=[]; REED_BUILT.root.updateMatrixWorld(true);
  REED_BUILT.root.traverse(function(o){ if(o.isMesh || o.isInstancedMesh) reedMeshes.push(o); });
  reedMeshes.forEach(function(o){ scene.attach(o); if(!o.userData.inspectLabel) o.userData.inspectLabel = 'The reed village (Reed Lake kit) · culture: reed-lake'; });
  var reedM = REEDKIT.KIT.meshes.hRLReed; if(reedM) reedM.userData.inspectLabel = 'Reed (living: the Reed Lake kit item) — flora · wet · tropic · abyssal · riparian: both · harvestable: thatch, mats, boats (the reed cutters)';
  var foot = REEDKIT.foot('rl_tavern');
  /* the budget: Locus's (05-palette.js) plus the draw calls the reed kit brings, one per kit item and mesh it made */
  var reedCalls = reedMeshes.length;
  BUDGET.drawCalls += reedCalls + 30;   /* +30: the life layer's moving meshes (people, mounts, boats, buggies) */
  window._reed = { islands:REED.islands.length, pads:REED.pads.length, buildings:REED_BUILT.placed.length, missing:REED_BUILT.missing,
    tavern:foot, reg:REED_BUILT.reg, drawCalls:reedCalls, instances:REED_BUILT.instances, lamps:REED_BUILT.lamps, meshes:REED_BUILT.meshes, ms:Math.round(performance.now()-t0) };
  TICKS.push(function(dt,hour,nk){ REEDKIT.setNight(nk > 0.3); });
  /* INTERIORS: the reed buildings are not ASSETs, so 66-locus-furnish.js's buildAsset hook never sees them. With
     ?interiors=1 each is planned and furnished from its Reed Lake interiors set item (kits/interiors/sets/reedlake.js,
     the reed defs' own frames: origin at the plot centre on the island top, +z the front) through the same catalog
     batch, just before the kit emits (75-terrain.js runs YUNI_FINISHERS). Counted in LOCF like the others. */
  (window.YUNI_FINISHERS = window.YUNI_FINISHERS || []).push(function(){
    if(!LOCF.interiors) return; var n=0;
    REED_BUILT.placed.forEach(function(p, i){ var b=p.b, v=b.v|0, it=LOCF.item(p.key, v);
      if(!it){ var w=LOCF.why(p.key, v), u=LOCF.unfurnished[w], k=p.key+(v?'#'+v:''); u[k]=(u[k]||0)+1; return; }
      var r=KratorInteriors.sets.furnish(it, b.x, b.z, b.ry||0, LOCF.adapter, { baseY:REED_Y, prefix:'rl.'+i+'.' });
      r.inst.rooms.forEach(function(R){ var P=r.plans[R.id]; (P&&P.lights||[]).forEach(function(l){ nlLampAdd(l.x, l.y, l.z, l.intensity||0.7, l.distance||10, false); }); });
      LOCF.buildings.push({ key:p.key, variant:v, x:b.x, z:b.z, ry:b.ry||0, reed:true, interior:{ item:it.key, rooms:r.inst.rooms.length, residence:r.residence } }); n++; });
    window._reed.furnished = n; });
})();
