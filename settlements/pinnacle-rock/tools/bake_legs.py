#!/usr/bin/env python3
"""Bake Pinnacle Rock's planned far legs: settlements/pinnacle-rock/src/14-pr-legs.js (PR_LEGS).

    python3 settlements/pinnacle-rock/tools/bake_legs.py           # write src/14-pr-legs.js
    python3 settlements/pinnacle-rock/tools/bake_legs.py --check   # exit 1 if the baked file is stale

core/simulation/PROPOSAL-LONGSONG-PINNACLE.md phase S5, the owner's answer (B), 2026-11-12. The bands' partners are 130 to
780 km out, beyond openworld/pinnacle's 60 km cut, so no baked link reaches them yet. Until a region lays those roads, each
leg is booked from the scale model:
  - the rock and each partner are read from the model's own settlement list (extract_region.load_model_defaults, map 5.1
    with its moves), never typed in, so a moved pin moves its leg (Shade is to move to an oasis farther north: the owner's
    answer 5 in openworld/PLAN-SETTLEMENTS.md);
  - the leg's length is the straight line times DETOUR;
  - its climb, descent and flat-equivalent km each way come from the model's heights (h.png) sampled every 2 km along the
    line, by core/world/48t-world-travel.js's own pace rule (Tobler's, normalised to the flat), each sample's run stretched
    by DETOUR;
  - the km over the model's water are counted (a leg the land route would go round).
Every leg is marked planned. core/camp reads them as KTRAVEL.graph `extra` edges keyed by the model's ids, so when a
region bakes the real links (claude/pinnacle-corridors) they replace these with no other change."""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
SM = os.path.join(ROOT, 'tools', 'scale-model')
sys.path.insert(0, SM)
import extract_region as XR   # noqa: E402
from PIL import Image          # noqa: E402

OUT = os.path.join(ROOT, 'settlements', 'pinnacle-rock', 'src', '14-pr-legs.js')
DETOUR, M_PER_PX, STEP_PX = 1.3, 2000.0, 1.0
ROCK = 'staiytii0y'
# the partners (the owner's answer 2): Iziz's port Goto and Nusidi (raids), the Beast Rider cities, the coyotemen, the Dasri
PARTNERS = [('ski7uk8fjc', 'Port Goto'), ('s2199308wr', 'Nusidi'), ('sghb3jlsk5', 'Talon'), ('s1kaqxmg10', 'Fort Kreia'),
            ('skukf2qmmq', "Mav's Refuge"), ('s5c6ysqazg', 'Fort Ordo'), ('seed07', 'Girder'), ('soksvzt1h9', 'Coyote Canyon'),
            ('slfozs6c7z', 'Shade')]


def slope_k(s):
    return math.exp(-3.5 * abs(s + 0.05)) / math.exp(-0.175)


def bake():
    M = {k['key']: k for k in json.load(open(os.path.join(SM, 'model', 'data', 'model.json'), encoding='utf-8'))['keys']}
    lo, hi = M['lo']['value'], M['hi']['value']
    H = Image.open(os.path.join(SM, 'model', 'data', 'h.png')).convert('RGB')
    W, Hh = H.size
    px = H.load()

    def height(x, y):   # bilinear on the full grid, and whether the nearest cell is water
        x = min(max(x, 0), W - 1.001); y = min(max(y, 0), Hh - 1.001)
        i, j = int(x), int(y); fx, fy = x - i, y - j
        def h(a, b):
            r, g, _ = px[a, b]; return lo + ((r << 8) | g) / 65535.0 * (hi - lo)
        v = (h(i, j) * (1 - fx) + h(i + 1, j) * fx) * (1 - fy) + (h(i, j + 1) * (1 - fx) + h(i + 1, j + 1) * fx) * fy
        return v, px[int(round(x)), int(round(y))][2] > 127
    S = {s['id']: s for s in XR.load_model_defaults('settlements')}
    R = S[ROCK]
    legs = {}
    for sid, name in PARTNERS:
        P = S[sid]
        dx, dy = P['px'] - R['px'], P['py'] - R['py']
        n = max(1, int(math.ceil(math.hypot(dx, dy) / STEP_PX)))
        pts = [height(R['px'] + dx * k / n, R['py'] + dy * k / n) for k in range(n + 1)]
        run = math.hypot(dx, dy) / n * M_PER_PX * DETOUR
        up = down = fwd = back = 0.0; wet = 0
        for k in range(n):
            d = pts[k + 1][0] - pts[k][0]
            up += max(0, d); down += max(0, -d)
            fwd += run / 1000 / slope_k(d / run); back += run / 1000 / slope_k(-d / run)
            if pts[k][1]: wet += 1
        legs[sid] = {'name': P['name'], 'px': P['px'], 'py': P['py'], 'x': dx * M_PER_PX, 'z': dy * M_PER_PX,
                     'length_m': round(run * n), 'up_m': round(up), 'down_m': round(down), 'fwd': round(fwd, 2), 'back': round(back, 2),
                     'wet_km': round(wet * run / 1000 / DETOUR), 'planned': True}
    return {'format': 'pinnacle-legs', 'version': 1, 'from': ROCK, 'px': [R['px'], R['py']], 'detour': DETOUR,
            'by': 'settlements/pinnacle-rock/tools/bake_legs.py (the scale model 5.1: its settlements and h.png)', 'legs': legs}


def text(D):
    return ('// ================================================================= PINNACLE ROCK — the planned far legs (S5)\n'
            '// [G data] GENERATED by settlements/pinnacle-rock/tools/bake_legs.py from the scale model (its settlements and heights):\n'
            '// do not edit; rerun it when a pin moves. Each leg from the rock to a partner: the straight line x ' + str(DETOUR) + ', its\n'
            '// climb and descent and flat-equivalent km each way from the model\'s heights every 2 km, marked planned until a region\n'
            '// lays the road (core/simulation/PROPOSAL-LONGSONG-PINNACLE.md, the owner\'s answer B of 2026-11-12).\n'
            'var PR_LEGS=' + json.dumps(D, ensure_ascii=False, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    t = text(bake())
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        print('fresh' if old == t else 'STALE: rerun bake_legs.py'); sys.exit(0 if old == t else 1)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(t)
    D = json.loads(t[t.index('var PR_LEGS=') + 12:-2])
    for k, L in D['legs'].items():
        print('  %-14s %-12s %6.0f km  up %5d m  down %5d m  water %3d km' % (L['name'], k, L['length_m'] / 1000, L['up_m'], L['down_m'], L['wet_km']))
    print('wrote', os.path.relpath(OUT, ROOT))
