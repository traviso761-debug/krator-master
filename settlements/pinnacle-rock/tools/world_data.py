#!/usr/bin/env python3
"""The surroundings as a page fragment: region/data (tools/scale-model/extract_region.py's cut round the site) decoded
here, at build time, into the typed arrays the open world's fields take (core/world/41-world-fields.js:
WORLD.init(R)); the decoder itself is core/world/world_data.py, so the page builds its land at once and never reads a canvas's pixels.

    fragment(region_dir) -> the JavaScript text of the generated fragment (WORLD_DATA, WORLD_R, WORLD_KITS)

The decoding is 98-world-start.js's, in Python: heights 16 bits in R,G (lo..hi), B the water flag; the map rasters one
byte each. Arrays go in as base64 of little-endian Float32 / Uint8, decoded by atob into typed arrays."""
import os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'core', 'world'))
import world_data as _core   # noqa: E402  (core/world/world_data.py: the decoder, lifted from here 2026-11-09)

HJ_KITS = "var WORLD_KITS=[{name:'hyperjungle',global:'HYPERJUNGLE',overlay:'hyperjungle'}];\n"


def fragment(region_dir, kits=None, name='39-pr-world-data.js'):
    """kits: the WORLD_KITS line (JavaScript) for another page that takes this decoder (settlements/longsong); name: its
    fragment's name in the header. The defaults are Pinnacle Rock's."""
    return _core.fragment(os.path.join(region_dir, 'data'), HJ_KITS if kits is None else kits,
                          name + ' (generated by build.py from region/data: do not edit)',
                          'the scale model round the site (tools/scale-model/extract_region.py), decoded at build time (tools/world_data.py)')


if __name__ == '__main__':
    print(len(fragment(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'region'))))
