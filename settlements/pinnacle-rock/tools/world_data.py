#!/usr/bin/env python3
"""The surroundings as a page fragment: region/data (tools/scale-model/extract_region.py's cut round the site) decoded
here, at build time, into the typed arrays the open world's fields take (openworld/little-demo/src/41-world-fields.js:
WORLD.init(R)), so the page builds its land at once and never reads a canvas's pixels.

    fragment(region_dir) -> the JavaScript text of the generated fragment (WORLD_DATA, WORLD_R, WORLD_KITS)

The decoding is 98-world-start.js's, in Python: heights 16 bits in R,G (lo..hi), B the water flag; the map rasters one
byte each. Arrays go in as base64 of little-endian Float32 / Uint8, decoded by atob into typed arrays."""
import base64, json, os
import numpy as np
from PIL import Image

MAP = ('clim', 'rain', 'temp', 'biome', 'mask')


def _rgb(path):
    return np.array(Image.open(path).convert('RGB')).astype(np.int64)


def fragment(region_dir):
    data = os.path.join(region_dir, 'data')
    meta = json.load(open(os.path.join(data, 'region.json'), encoding='utf-8'))
    lo, hi = meta['heights']['lo'], meta['heights']['hi']
    v16 = lambda a: lo + ((a[..., 0] << 8) | a[..., 1]) / 65535.0 * (hi - lo)
    e, w = _rgb(os.path.join(data, 'elev.png')), _rgb(os.path.join(data, 'wlev.png'))
    R = {'elev': v16(e).astype('<f4'), 'wflag': (e[..., 2] > 127).astype('u1'), 'whas': (w[..., 2] > 127).astype('u1')}
    R['wlev'] = np.where(R['whas'] > 0, v16(w), lo).astype('<f4')
    for k in MAP:
        R[k] = _rgb(os.path.join(data, k + '.png'))[..., 0].astype('u1')
    R['scarpL'] = v16(_rgb(os.path.join(data, 'scarpl.png'))).astype('<f4')
    R['scarpU'] = v16(_rgb(os.path.join(data, 'scarpu.png'))).astype('<f4')
    R['scarpW'] = _rgb(os.path.join(data, 'scarpw.png'))[..., 0].astype('<f4')
    enc = {k: [('f4' if v.dtype.kind == 'f' else 'u1'), base64.b64encode(np.ascontiguousarray(v).ravel().tobytes()).decode('ascii')] for k, v in R.items()}
    return ('// ==================== 39-pr-world-data.js (generated by build.py from region/data: do not edit)\n'
            '// the scale model round the site (tools/scale-model/extract_region.py), decoded at build time (tools/world_data.py)\n'
            'var WORLD_DATA={meta:' + json.dumps(meta, separators=(',', ':'), ensure_ascii=False) + '};\n'
            'var WORLD_R=(function(E){const R={};for(const k in E){const b=atob(E[k][1]),u=new Uint8Array(b.length);'
            'for(let i=0;i<b.length;i++)u[i]=b.charCodeAt(i);R[k]=E[k][0]===\'f4\'?new Float32Array(u.buffer):u;}return R;})('
            + json.dumps(enc, separators=(',', ':')) + ');\n'
            # the kits the fields know: the hyperjungle grows on this page's floor (the others' overlays are drawn far off)
            "var WORLD_KITS=[{name:'hyperjungle',global:'HYPERJUNGLE',overlay:'hyperjungle'}];\n")


if __name__ == '__main__':
    import sys
    print(len(fragment(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'region'))))
