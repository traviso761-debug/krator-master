#!/usr/bin/env python3
"""The Marches' west and south watch forts on a sheet (PLAN.md, steps M1 and M3; settlements/xanadu/BUILD-PLAN.md, A8).

The page is Xanadu's, as Strongwall's, Qiblai's and Kirstabal's are: settlements/xanadu/build.py --kit takes this folder's kit.json,
src/ (the outside works the kit lacks: the wayside shrine, the stable yard's cistern, the road) and targets/forts/, with the Xanadui
fort read in place from kits/xanadu (src/80f-xa-fort-data.js, XFORT; src/80g-xa-fort.js, its drawing: kit.json "external"). Flat
ground: Marchiz is cut after the vertical stack (the owner, 2026-11-22), so the forts are drawn here and placed on their ground at M2.

The tune (gen/69m-mr-tune.js): core/region/data/xan-tune.js, the file as it is, written under a numbered name at every build so it
loads before the sheet's rows (the page is one script in the fragments' name order; a bare xan-tune.js would sort after 99-start.js).
Never edited, never committed (.gitignore): the page reads the forts' records from XAN_TUNE itself (XAN_TUNE.valley, T.muskets).

    python3 ../../tools/build.py settlements/marches      # dist/marches.html
    python3 verify.py dist/marches.html --assert --views "Both forts kept,The west fort kept"
"""
import io, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import buildlib                                   # noqa: E402
buildlib.through_tools_build(__file__)            # item 25: build-inputs.json is always written
import build_sources as BSRC                      # noqa: E402  (--list-sources: tools/dep_graph.py)

# the core modules this page takes (through Xanadu's build and kit.json "external"): core/rand, core/tags, core/host, core/door,
# core/walk, core/terrain (KRUBBLE), core/ruins, core/region (XAN_TUNE), core/drawn
CORE_TAKEN = ('core/rand', 'core/tags', 'core/host', 'core/door', 'core/walk', 'core/terrain', 'core/ruins', 'core/region', 'core/drawn')

TUNE = 'core/region/data/xan-tune.js'
GEN = os.path.join(HERE, 'gen')


def write_gen():
    os.makedirs(GEN, exist_ok=True)
    with io.open(os.path.join(ROOT, *TUNE.split('/')), encoding='utf-8') as fh:
        body = fh.read()
    new = ('// GENERATED by settlements/marches/build.py at every build: %s as it is, under a numbered name so it loads before the\n'
           '// sheet\'s rows (targets/forts/89z-rows.js). Edit the tune, never this. [G data]\n' % TUNE) + body
    out = os.path.join(GEN, '69m-mr-tune.js')
    old = io.open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if old != new:
        with io.open(out, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(new)


BSRC.note(TUNE)
if not BSRC.LISTING:
    write_gen()

if '--no-checks' not in sys.argv:
    if subprocess.call([sys.executable, os.path.join(ROOT, 'tools', 'check_port.py'), '--quiet', HERE]) != 0:
        sys.exit('build.py: the port lint failed (tools/check_port.py); fix the fragment or retag it in PORT.md')

_rc = subprocess.call([sys.executable, os.path.join(ROOT, 'settlements', 'xanadu', 'build.py'), '--kit', HERE] + sys.argv[1:],
                      cwd=os.path.join(ROOT, 'settlements', 'xanadu'))
if not _rc:
    BSRC.report()
sys.exit(_rc)
