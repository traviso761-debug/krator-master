var EDITS = { removed:{}, moved:{}, added:{} };              /* removed[id] = key; moved[id] = { key, x, y, z, ry }; added[unit i] = [piece] */
/* kept by the host (57c: this browser's storage); here only data. MIX.edit.import() brings a saved set back */
function editsSave(){ if(MIX.onEditsSaved) MIX.onEditsSaved(EDITS); }
function unitOfPiece(id){ var m = /^mix\.(\d+)\./.exec(id||''); return m ? +m[1] : -1; }
