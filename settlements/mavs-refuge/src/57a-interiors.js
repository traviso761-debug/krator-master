/* ------------------------------------------------------------------ lights: every piece's, from the catalog (per key and variant) */
var LIGHTS = {};
function lightsOfPiece(p){
  var k = p.key+'|'+p.v, L = LIGHTS[k];
  if(!L) L = LIGHTS[k] = KF.has(p.key) ? KF.lightsOf(p.key, p.v, 1, 0.5) : [];
  if(!L.length) return [];
  var c = Math.cos(p.ry), s = Math.sin(p.ry), hearth = p.type==='stove' || p.type==='brazier' || /hearth|forge|fire|stove|brazier/.test(p.key);
  return L.map(function(l){ return { x:p.x + l.x*c + l.z*s, y:p.y + l.y, z:p.z - l.x*s + l.z*c, color:l.color, intensity:l.intensity==null?1:l.intensity,
                                     distance:l.distance||6, hearth:hearth, piece:p.id }; });
}
function lightsOfRecord(u, rec){
  var out = [];
  rec.pieces.forEach(function(p){ lightsOfPiece(p).forEach(function(l){
    var Lv = rec.B.levels[p.level] || rec.B.levels[0]; l.floor = Lv.y; l.ceil = Lv.y + Lv.h; out.push(l); }); });
  return out;
}
/* into the night light volume: before the bake (nlIxAdd), or queued for nlvAddIx after it. [amp, radius]: the volume's
   8 m cells pool a room's light into its neighbours', so it is kept low (the pool in 57c lights the room itself) */
var IX_NLV = { lamp:[0.2, 6], hearth:[0.28, 7] };
function registerLights(rec, before){
  rec.lights.forEach(function(l){
    var L = [l.x, l.y, l.z, l.hearth ? IX_NLV.hearth[0] : IX_NLV.lamp[0], l.hearth ? IX_NLV.hearth[1] : IX_NLV.lamp[1]];
    if(before) nlIxAdd(L[0], L[1], L[2], L[3], L[4]); else MIX.ixPending.push(L);
    MIX.ixLights++;
  });
}

/* ------------------------------------------------------------------ the record: plan + pieces (+ lights), kept */
function mixRecord(i){
  var u = MIX.units[i]; if(!u) return null;
  if(MIX.rec[i]) return MIX.rec[i];
  var pl = mixPlan(u, !!(u.bake && u.bake.fb)), B = pl.B, rec;     /* a baked unit replays its plan (fb: the fallback was forced) */
  if(u.bake){
    var bk = u.bake;
    rec = { B:B, dropped:pl.dropped, pieces:bk.p.map(function(a){ return pieceFromBake(u, B, MIX.bakeKeys, a); }), residence:bk.r || null, missing:bk.m || [],
            from:'bake', forced:!!bk.fb };
    MIX.fromBake++;
  } else {
    var F = mixFurnish(u, B);
    /* a home that still fails the residence rule (a food 'container' that is only a pot on the table, say) is
       planned again with its fallback programme (a cottage: bed, hearth, chest and food in one room) */
    if(u.dwelling && F.residence && !F.residence.ok && u.fallback && !u.usedFallback){
      var pl2 = mixPlan(u, true), F2 = mixFurnish(u, pl2.B);
      if(F2.residence && F2.residence.ok){ pl = pl2; B = pl2.B; F = F2; var forced = true; } else u.usedFallback = false;
    }
    rec = { B:B, dropped:pl.dropped, pieces:F.pieces, residence:F.residence, missing:F.missing, from:'computed', forced:!!forced };
    MIX.computed++;
  }
  rec.lights = lightsOfRecord(u, rec);
  if(!u.lightsIn){ registerLights(rec, false); u.lightsIn = true; }
  rec.info = { id:u.id, kind:u.kind, label:u.label, rooms:B.rooms.map(function(R){ return R.kind; }), floors:B.levels.length, stairs:B.stairs.length,
    pieces:rec.pieces.length, lights:rec.lights.length, dropped:rec.dropped, missing:rec.missing, residence:rec.residence, fallback:!!u.usedFallback, from:rec.from,
    windows:B.rooms.reduce(function(a,R){ return a + (R.windowsFromFacade||0); }, 0) };
  if(u.site) u.site.interior = rec.info;
  if(u.dwelling && rec.residence && !rec.residence.ok && MIX.fails.indexOf(u.id)<0) MIX.fails.push(u.id);
  if(rec.dropped.length && MIX.dropped.indexOf(u.id)<0) MIX.dropped.push(u.id);
  MIX.rec[i] = rec;
  return rec;
}
