function arcPts(P, r, a0, a1, step){
  var n = Math.max(1, Math.ceil(Math.abs(a1-a0)*Math.max(r,1)/(step||1.6))), out = [];
  for(var i=0;i<=n;i++){ var p = platXZ(P, r, a0+(a1-a0)*i/n); out.push([R3(p[0]), R3(p[1])]); }
  return out;
}
/* an annular sector r0..r1 x a0..a1, each side set in by `ins` metres. The inner arc is concave seen from inside:
   where it sags less than 0.3 m it is drawn as a chord (into the core wall), so the planner sees one straight wall.
   .front is the outer arc's polyline (the walls the builder drew there have an inner face of their own) */
function sectorPoly(P, r0, r1, a0, a1, ins){
  ins = ins||0;
  var o = arcPts(P, r1, a0+ins/r1, a1-ins/r1), ia0 = a0+ins/Math.max(r0,1), ia1 = a1-ins/Math.max(r0,1), inner;
  if(ia1-ia0 < 0.02) inner = [platXZ(P, r0, (a0+a1)/2)];
  else if(r0*(1-Math.cos((ia1-ia0)/2)) < 0.3){ var p1=platXZ(P,r0,ia1), p0=platXZ(P,r0,ia0); inner = [p1, p0]; }
  else inner = arcPts(P, r0, ia1, ia0);
  var poly = o.concat(inner.map(function(p){ return [R3(p[0]), R3(p[1])]; }));
  poly.front = o;
  return poly;
}
function polyArea(po){ var a=0; for(var i=0;i<po.length;i++){ var p=po[i], q=po[(i+1)%po.length]; a += p[0]*q[1]-q[0]*p[1]; } return Math.abs(a)/2; }
function at(P, r, a){ var p = platXZ(P, r, a); return [R3(p[0]), R3(p[1])]; }
/* a builder's window { a, hw, y0, y1 } on an arc face at radius r, as a planner window on storey `level` (floor y) */
