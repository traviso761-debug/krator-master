/* ------------------------------------------------------------------ plan (cheap: always computed) */
function segD(p, a, b){ var vx=b[0]-a[0], vz=b[1]-a[1], L=vx*vx+vz*vz, t=L>0?clamp(((p[0]-a[0])*vx+(p[1]-a[1])*vz)/L,0,1):0; return Math.hypot(p[0]-a[0]-vx*t, p[1]-a[1]-vz*t); }
function polyD(p, po){ var m=1e9; for(var i=0;i<po.length;i++) m=Math.min(m, segD(p, po[i], po[(i+1)%po.length])); return m; }
function mixPlan(u, useFallback){
  var t0 = performance.now(), opts = { seed:0, register:false, door:0.9, minWidth:2.0 };
  var B = IX.planBuilding(u.shell, useFallback && u.fallback ? u.fallback : u.program, opts);
  var dropped = function(B){ return (B.report.dropped||[]).map(function(x){ return (x.kinds||[]).join('+'); }); };
  var dr = dropped(B);
  if(useFallback) u.usedFallback = true;
  else if(dr.length && u.fallback){ var B2 = IX.planBuilding(u.shell, u.fallback, opts); if(dropped(B2).length < dr.length || !B.rooms.length){ B = B2; dr = dropped(B2); u.usedFallback = true; } }
  /* the builder's windows become the rooms' windows (the planner was asked for none): each to the room whose wall it is on */
  var own = u.wins.map(function(w){ var best = -1, bd = u.shell.wall + 0.45;
    B.rooms.forEach(function(R, k){ if(R.level !== w.level) return; var d = polyD(w.at, R.poly); if(d < bd){ bd = d; best = k; } }); return best; });
  if(u.wins.length) B.rooms = B.rooms.map(function(R, k){
    var def = B.roomDefs[k], ws = u.wins.filter(function(w, j){ return own[j] === k; });
    if(!ws.length) return R;
    def.windows = ws.map(function(w){ return { at:w.at, w:w.w, sill:w.sill, h:w.h }; });
    try{ var N = IX.normRoom(def); N.windowsFromFacade = ws.length; return N; }catch(e){ def.windows = []; return R; }
  });
  MIX.msPlan += performance.now()-t0;
  return { B:B, dropped:dr };
}
/* the residence rule over a unit's plans (IX.sets.auditResidence's count, for one unit) */
function mixResidence(pieces){
  var FOOD = IX.FOOD_ROLES||[], ITEM = IX.ITEM_ROLES||[], o = { beds:0, food:0, items:0 };
  pieces.forEach(function(p){
    if(p.type==='bed') o.beds += p.catRole==='bunk' ? 2 : 1;
    if(p.catRole && FOOD.indexOf(p.catRole)>=0 && (p.type==='storage'||p.type==='vessel'||p.type==='stack') && p.anchor!=='surface') o.food++;
    if(p.catRole && ITEM.indexOf(p.catRole)>=0 && p.type==='storage') o.items++;
  });
  o.ok = o.beds>=1 && o.food>=1 && o.items>=1;
  return o;
}
/* furnish (the costly part): the plans' placements, as piece records */
function mixFurnish(u, B){
  var t0 = performance.now(), plans, pieces, res = null, seed = 0;
  for(var att=0; att<6; att++){
    plans = B.rooms.map(function(R){ return IX.furnishRoom(R, MIX.adapter, { seed:seed }); });
    pieces = piecesOf(u, B, plans);
    if(!u.dwelling) break;
    res = mixResidence(pieces); if(res.ok) break;
    seed += 101;
  }
  var missing = [];
  plans.forEach(function(pl, k){ (pl.report.missing||[]).forEach(function(m){ missing.push(B.rooms[k].kind+':'+m.need); }); });
  MIX.msFurnish += performance.now()-t0;
  return { pieces:pieces, residence:res, missing:missing };
}
