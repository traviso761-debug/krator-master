#!/usr/bin/env python3
"""The Iziz palace citadel's blueprint as data for the pages: writes settlements/iziz/targets/palace/78p-palace-plan.js (the palace page's
target; it moves to src/ when the city takes the palace) from
iziz_blueprint.py's FLOORS (the same rooms the sheets in floors/ draw).

    python3 export_plan.py          # after editing iziz_blueprint.py (the sheets: python3 iziz_blueprint.py)

Each sheet keeps its rooms as [n, name, kind, u0, u1, v0, v1, decor, note] in the citadel's frame (u from the gate
inward, v across, metres; BLUEPRINT.md), its doors [u, v] where it has them, and the stairs and shafts that line up
from sheet to sheet. Which storey takes which sheet, the heights, and what each kind becomes is 78q-palace-layout.js's."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import iziz_blueprint as B

OUT = os.path.join(HERE, '..', 'targets', 'palace', '78p-palace-plan.js')


def r2(v):
    return round(float(v), 2)


def main():
    B.domus_passage()
    sheets = {}
    for F in B.FLOORS:
        S = {'tier': F['tier'], 'title': F['title'],
             'rooms': [[r['n'], r['name'], r['kind'], r2(r['u0']), r2(r['u1']), r2(r['v0']), r2(r['v1']), r['decor'], r.get('note', '')]
                       for r in F['rooms']]}
        if 'doors' in F:
            S['doors'] = [[r2(a), r2(b)] for a, b in F['doors']]
        sheets[F['id']] = S
    stairs = {'well': B.WELL, 'great': B.GSTAIR, 'depot': B.DSTAIR, 'tower': B.TSTAIR, 'core': B.CSTAIR}
    js = ('/* ============================== 78p. THE PALACE CITADEL BLUEPRINT (data) ============================== */\n'
          '/* [G data] GENERATED by settlements/iziz/palace/export_plan.py from palace/iziz_blueprint.py (the owner\'s agreed\n'
          '   programme, 2026-10-15: palace/BLUEPRINT.md and the sheets in palace/floors/). Do not edit: change the blueprint and\n'
          '   rerun the exporter. A sheet\'s rooms are [n, name, kind, u0, u1, v0, v1, decor, note] in the citadel\'s frame (u from\n'
          '   the gate inward, v across, metres); 78q-palace-layout.js lays them out. */\n'
          'const IZPAL_PLAN=' + json.dumps({'sheets': sheets, 'stairs': {k: [r2(x) for x in v] for k, v in stairs.items()}},
                                           separators=(',', ':'), ensure_ascii=False) + ';\n')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(js)
    n = sum(len(s['rooms']) for s in sheets.values())
    print('wrote', os.path.relpath(OUT, HERE).replace(os.sep, '/'), len(sheets), 'sheets,', n, 'rooms,', len(js) // 1024, 'KB')


if __name__ == '__main__':
    main()
