#!/usr/bin/env python3
"""Write tex/kf-tex.js, the KF_TEX the Voth catalog page loads (index.html) for core/catalog's detail maps
(krator-furniture-detail.js: KF_API.detailize). Same shape as kits/beast-riders/build.py kf_tex(), but each map is the
packed file's URL relative to the page (the page is served, it is not a single file), so this stays a few hundred bytes.

    python3 tools/textures/pack.py settlements/voth/catalog     # materials.json -> tex/*.webp + tex/pack.json
    python3 settlements/voth/catalog/kftex.py                   # tex/pack.json -> tex/kf-tex.js
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    with open(os.path.join(HERE, 'tex', 'pack.json'), encoding='utf-8') as fh:
        pack = json.load(fh)
    out = {}
    for fam, e in sorted(pack['families'].items()):
        name = e['files'].get('map')
        if name:
            out[fam] = {'lib': e['lib'], 'scale': e['scale'][0], 'mean': e['tint']['mean'], 'map': 'tex/' + name}
    js = ('/* GENERATED by kftex.py from tex/pack.json (materials.json via tools/textures/pack.py): the catalog page\'s '
          'detail maps for core/catalog/krator-furniture-detail.js */\nconst KF_TEX = %s;\n' % json.dumps(out, sort_keys=True))
    with open(os.path.join(HERE, 'tex', 'kf-tex.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(js)
    print('wrote tex/kf-tex.js: %d families' % len(out))


if __name__ == '__main__':
    main()
