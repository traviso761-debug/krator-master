/* ======================================================================
   Voth — structures captured from the live city build
   GENERATED by catalog/capture/capture.py — edit the generator, not this.

   Every entry here is a structure the city generator (voth/src/) builds,
   pulled out of a real build: cantons, the Palace and Temple tops, the
   Ordinator fortress on the Lighthouse canton, bridges, causeways, walls,
   gates and towers, graves, tombs and the funerary temple, taverns, mills,
   the monastery, town houses and compounds, market stalls, and the life
   layer's ships, barges and carts.

   Each variant is one representative call from the city, replayed from its
   recorded primitives (registry/voth-city-captured.data.js) in the city's own
   shapes (battered frustums fr8/fr6/fr3, domes, stalks, 6-sided cones).
   These are reference geometry, not parametric builders: to make a new
   variation, copy the builder named in `srcFn` from voth/src into a new
   registry entry and edit it there, using the captured one as the target.
   ====================================================================== */
(function () {
  'use strict';
  const META = /*__META__*/[];
  const D = window.VOTH_CITY_CAPTURE;
  if (!D) { console.error('voth-city-captured: data file not loaded'); return; }

  /* the city's unit shapes (voth/src/45-kit.js SHAPES), base at y = 0 */
  function rectFrus(t) {
    const b = 0.5, X = t * 0.5, Z = t * 0.5;
    const v = [[-b, 0, -b], [b, 0, -b], [b, 0, b], [-b, 0, b], [-X, 1, -Z], [X, 1, -Z], [X, 1, Z], [-X, 1, Z]];
    const faces = [[0, 1, 5, 4], [1, 2, 6, 5], [2, 3, 7, 6], [3, 0, 4, 7], [4, 5, 6, 7], [3, 2, 1, 0]];
    const pos = [];
    faces.forEach((f) => [[0, 2, 1], [0, 3, 2]].forEach((tr) => tr.forEach((k) => pos.push(v[f[k]][0], v[f[k]][1], v[f[k]][2]))));
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
    g.computeVertexNormals();
    return g;
  }
  const GEO = {
    box: () => new THREE.BoxGeometry(1, 1, 1).translate(0, 0.5, 0),
    fr8: () => rectFrus(0.86), fr6: () => rectFrus(0.60), fr3: () => rectFrus(0.26),
    dome: () => new THREE.SphereGeometry(1, 16, 8, 0, TAU, 0, Math.PI * 0.5),
    blob: () => new THREE.SphereGeometry(1, 8, 5, 0, TAU, 0, Math.PI * 0.5),
    cyl: () => new THREE.CylinderGeometry(1, 1, 1, 10).translate(0, 0.5, 0),
    stk: () => new THREE.CylinderGeometry(0.8, 1, 1, 6).translate(0, 0.5, 0),
    cone: () => new THREE.ConeGeometry(1, 1, 6).translate(0, 0.5, 0)
  };
  const CACHE = {};
  const geo = (s) => CACHE[s] || (CACHE[s] = GEO[s]());
  const meshMat = new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 0.85 });

  function replay(F, recs) {
    const c = Math.cos(F.ry), s = Math.sin(F.ry);
    for (const r of recs) {
      const fam = D.fams[r[1]] === 'metal' ? 'metal' : undefined;
      if (r[0] === 9) {
        F.beam(r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], D.cols[r[10]], fam);
        continue;
      }
      const m = new THREE.Mesh(geo(D.shapes[r[0]]), mat(D.cols[r[9]], fam));
      m.position.set(F.x + r[2] * c + r[4] * s, F.y + r[3], F.z - r[2] * s + r[4] * c);
      m.scale.set(Math.max(r[5], 0.01), Math.max(r[6], 0.01), Math.max(r[7], 0.01));
      m.rotation.y = F.ry + r[8];
      _add(m);
    }
  }
  function replayMesh(F, v) {
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(v.p, 3));
    if (v.c) g.setAttribute('color', new THREE.Float32BufferAttribute(v.c, 3));
    g.computeVertexNormals();
    const m = new THREE.Mesh(g, v.c ? meshMat : mat(0x8a7a62));
    m.position.set(F.x, F.y, F.z);
    m.rotation.y = F.ry;
    _add(m);
  }

  for (const M of META) {
    const vs = D.entries[M.key];
    if (!vs) continue;
    ASSET({
      key: M.key, name: M.name, culture: 'voth', family: M.family, source: 'voth-city-captured',
      srcFn: M.fn, srcAt: M.src, cityCount: M.count,
      blurb: M.name + ' — ' + M.count + ' in the city, built at voth/src/' + M.src,
      districts: [], wealth: [0, 1],
      w: M.w, d: M.d, h: M.h, variants: vs.length, variantDims: M.variantDims,
      build: function (F) {
        const v = vs[Math.min(F.variant, vs.length - 1)];
        if (v.m) replayMesh(F, v); else replay(F, v.r);
      }
    });
  }
})();
