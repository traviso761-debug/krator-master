#!/usr/bin/env python3
"""The Palace blueprint as data for the city page: writes targets/voth-city/40c-vc-palace-plan.js from blueprint.py's FLOORS.

    python3 export_plan.py          # after editing blueprint.py (the sheets: python3 blueprint.py)

Each sheet keeps its rooms as [n, name, kind, u0, u1, v0, v1, decor] in the suite's frame (u along the axis in from the
-x face, v across, metres), plus its pillars, octagon, dais and garden doors where it has them. Which storey takes which
sheet, and what each kind becomes in the city, is 40d-vc-blueprint.js's and TUNE.interiors.blueprint's."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import blueprint as B

OUT = os.path.join(HERE, '..', 'targets', 'voth-city', '40c-vc-palace-plan.js')

def r1(v):
    return round(float(v), 2)

def main():
    sheets = {}
    for F in B.FLOORS:
        S = {'tier': F['tier'], 'R': F['R'], 'title': F['title'],
             'rooms': [[r['n'], r['name'], r['kind'], r1(r['u0']), r1(r['u1']), r1(r['v0']), r1(r['v1']), r['decor']] for r in F['rooms']]}
        for k in ('pillars', 'octagon', 'dais', 'doors'):
            if k in F: S[k] = [list(map(r1, q)) if isinstance(q, (list, tuple)) else r1(q) for q in F[k]]
        sheets[F['id']] = S
    js = ('/* ============================== 5h3. THE PALACE BLUEPRINT (data) ============================== */\n'
          '/* [G data] GENERATED by settlements/voth/palace/export_plan.py from palace/blueprint.py (the owner\'s floor-by-floor\n'
          '   blueprint, 2026-10-15: palace/BLUEPRINT.md). Do not edit: change blueprint.py and rerun the exporter. A sheet\'s rooms\n'
          '   are [n, name, kind, u0, u1, v0, v1, decor] in the suite\'s frame (40b-vc-suites.js); 40d-vc-blueprint.js lays them out. */\n'
          'VC.PALACE_PLAN = ' + json.dumps({'sheets': sheets, 'stairs': {
              'core': B.CORE, 'servants': B.SWAY, 'kitchen': B.KSTAIR, 'chancery': B.CSTAIR, 'gaol': B.GSTAIR, 'inner': B.ISTAIR, 'secret': B.XSTAIR}},
              separators=(',', ':'), ensure_ascii=False) + ';\n')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh: fh.write(js)
    n = sum(len(s['rooms']) for s in sheets.values())
    print('wrote', os.path.relpath(OUT, HERE), len(sheets), 'sheets,', n, 'rooms,', len(js) // 1024, 'KB')

if __name__ == '__main__':
    main()
