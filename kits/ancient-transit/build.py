#!/usr/bin/env python3
"""Concatenate the fragments (filename order) into dist/ancient-transit.html: the Ancient Transit kit's demo page (PLAN.md).

  00-head.html        page shell, opens <script>
  06..34              core/shader, core/export, core/rand, the biome core (core/biome: BIO.init, the records), core/shadow, core/clock,
                      core/space, core/walk, core/materials/record (KMAT: the library's maps)
  40-44               [G data] THE KIT'S RECORDS: kinds and shares, the path and profile, the highway, the rail lines and trains, the
                      street dress (tests/test-transit.js runs them in node)
  44z                 (generated) the kit's library pack (tex/, materials.json), as a sidecar beside the page (--inline-packs: in the page)
  45, 47              HOST: renderer, light, the ground's height; the ground mesh, BIO.init, the shadows
  49                  (generated) the furniture bundle: the catalog core, the `ancient` pieces, the assembler, in ONE closure
                      (transit_bundle.furniture(): the global KratorTransitFurniture)
  49b                 (generated) the Ancient vehicles (kits/motor-vehicles vehicle_bundle.bundle(['ancient']): KratorVehicles) for the blockades
  46                  [draw] the library materials and the geometry builder (46-tr-mats)
  50-53               core/tags
  55-57               [draw] THE KIT'S DRAWING: the highway, the rail lines and trains, the street dress and the roads
  70                  HOST: the test stage (what stands where), the views
  89..98              core/atmos (the shared sky), core/host
  99                  the page handed to core/host; 99-tail.html closes <script>

Another build takes the kit as biomes/ancientsvalley takes kits/metropolis: the src/ fragments by path (transit_bundle.fragments())
and the furniture bundle as a generated fragment (transit_bundle.furniture()); its library pack with tools/textures/matlib_pack.py
under the name 'ancient-transit'. Usage: python3 build.py [--no-checks] [--inline-packs]
"""
import hashlib, json, os, re, subprocess, sys, importlib.util

import os as _os, subprocess as _sp, sys as _sys
_cp = _os.path.join(_os.path.dirname(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))), 'tools', 'check_port.py')
if _os.path.isfile(_cp) and '--no-checks' not in _sys.argv and \
        _sp.call([_sys.executable, _cp, '--quiet', _os.path.dirname(_os.path.abspath(__file__))]) != 0:
    _sys.exit('build.py: the port lint failed (tools/check_port.py); fix the fragment or retag it in PORT.md')

try:
    sys.stdout.reconfigure(encoding='utf-8')
except Exception:
    pass

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, 'src'); DIST = os.path.join(HERE, 'dist'); OUT = 'ancient-transit.html'
CORE = os.path.join(ROOT, 'core')


def find_node():
    import shutil
    return os.environ.get('NODE') or shutil.which('node')


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path); m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m


PATH = {f: os.path.join(SRC, f) for f in os.listdir(SRC) if not f.startswith('.')}


def core(folder, names):
    for f in names:
        if f not in PATH:
            PATH[f] = os.path.join(CORE, folder, f)


# core/rand: every draw in the kit is a KRAND hash (40-44); core/tags: every registered volume a record (BIO.init({tags}), 47)
core('rand', ['08-core-rand.js'])
core('tags', ['50-core-tags.js', '52-core-tags-vocab.js', '53-core-tags-host.js'])
core('space', ['20-core-space.js'])   # KSPACE: the dress keeps its pieces apart and off the host's pads (44, 70)
core('shadow', ['10-core-shadow.js'])
core('shadow/host', ['12-core-shadow-host.js'])
core('walk', ['20-core-walk.js'])
core('biome', ['10-core-head.js', '20-core-kit.js', '30-core-foliage.js', '31b-core-leafset.js', '34-core-impostor.js', '40-core-place.js', '42-core-export.js', '43-core-export-host.js'])
core('export', ['07-core-export.js', '09-core-export-adapters.js'])
core('materials/record', ['23-mat-record.js', '25-matlib-host.js'])
core('atmos', ['89-atmos-0-core.js', '89-atmos-0p-presets.js'])
core('atmos/sky', ['89-atmos-e-skymodel.js', '89-atmos-f-skypresets.js', '89-atmos-g-sky.js'])
core('atmos/host', ['89-atmos-h-skyhost.js', '89-atmos-i-skybiome.js'])
sys.path.insert(0, os.path.join(CORE, 'host'))
import host as khost
khost.resolve(PATH, khost.SHELL + ['94-host-polytool.js'])
sys.path.insert(0, os.path.join(ROOT, 'tools', 'textures'))
import matlib_pack as _mp
sys.path.insert(0, HERE)
import transit_bundle
SIDE = None if '--inline-packs' in sys.argv else {}
VIRTUAL = {'44z-host-matlib-pack.js': _mp.fragment(HERE, 'ancient-transit', side=SIDE, own=True),
           '49-tr-furniture-bundle.js': '/* GENERATED by build.py */\n' + transit_bundle.furniture()}
# THE ANCIENT VEHICLES (kits/motor-vehicles, culture `ancient`: the vehicles session's branch, merged here 2026-11-09): the blockades' wrecks. The
# bundle rides along only when that culture file exists; without it the page draws burnt hulks (KTRANSIT.draw.vehicles)
VEH = os.path.join(ROOT, 'kits', 'motor-vehicles')
if os.path.isfile(os.path.join(VEH, 'krator-vehicles-ancient.js')):
    sys.path.insert(0, VEH)
    import vehicle_bundle
    VIRTUAL['49b-tr-vehicles-bundle.js'] = '/* GENERATED by build.py: kits/motor-vehicles vehicle_bundle.bundle([ancient]) */\n' + vehicle_bundle.bundle(['ancient'])
for f in VIRTUAL:
    PATH[f] = None

RE_DECL = re.compile(r'^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)', re.M)


def check(frags):
    """the kit's own fragments: no top-level name declared twice, no trailing // after code on a packed line (tools/check_source.py TRAILING)"""
    errs, decl = [], {}
    for f in frags:
        if PATH[f] is None or not f.endswith('.js') or not PATH[f].startswith(SRC):
            continue
        body = open(PATH[f], encoding='utf-8').read()
        for m in RE_DECL.finditer(body):
            decl.setdefault(m.group(1), set()).add(f)
        for i, ln in enumerate(body.split('\n'), 1):
            code = re.sub(r'/\*.*?\*/', '', ln)
            if re.search(r'[;}]\s*//', code) and not code.lstrip().startswith('//') and 'http' not in code:
                errs.append('%s:%d: a // comment after code on a packed line (write /* */)' % (f, i))
    for n, fs in sorted(decl.items()):
        if len(fs) > 1:
            errs.append('top-level name `%s` declared in more than one fragment: %s' % (n, ', '.join(sorted(fs))))
    return errs


frags = sorted(PATH); out = []
if '--no-checks' not in sys.argv:
    errs = check(frags)
    if errs:
        print('BUILD RULES FAILED:'); [print('  -', e) for e in errs]; sys.exit(1)
for f in frags:
    s = VIRTUAL[f] if PATH[f] is None else open(PATH[f], encoding='utf-8').read()
    out.append('\n// ==================== %s\n' % f if f.endswith('.js') else ''); out.append(s)
html = ''.join(out)
os.makedirs(DIST, exist_ok=True)
if SIDE:
    html = _mp.write_sidecar(SIDE, html, DIST, 'ancient-transit.tex.js')
with open(os.path.join(DIST, OUT), 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(html)
m = re.search(r'<script>\n(?!document)(.*)</script>\s*</body>', html, re.S)
chk = os.path.join(HERE, '.syntax.js')
with open(chk, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(m.group(1) if m else '')
node = find_node()
r = subprocess.run([node, '--check', chk], capture_output=True, text=True) if node else None
inputs = {}
for f in frags:
    if PATH[f]:
        with open(PATH[f], 'rb') as fh:
            inputs[os.path.relpath(PATH[f], ROOT).replace(os.sep, '/')] = hashlib.sha1(fh.read()).hexdigest()
for d, f in transit_bundle.files():
    with open(os.path.join(d, f), 'rb') as fh:
        inputs[transit_bundle.label(d, f)] = hashlib.sha1(fh.read()).hexdigest()
with open(os.path.join(HERE, 'build-manifest.json'), 'w', encoding='utf-8', newline='\n') as fh:
    json.dump(inputs, fh, indent=0, sort_keys=True)
print('built dist/%s  (%d fragments, %d KB)  %s' % (OUT, len(frags), len(html) // 1024, 'syntax NOT CHECKED (no node)' if r is None else 'syntax OK' if r.returncode == 0 else 'SYNTAX ERROR\n' + r.stderr[:1500]))
ki = os.path.join(HERE, 'KNOWN_ISSUES.md')
if os.path.exists(ki):
    op = [l for l in open(ki, encoding='utf-8') if l.startswith('- [ ]')]
    if op:
        print('KNOWN_ISSUES.md: %d open item(s)' % len(op))
sys.exit(r.returncode if r else 0)
