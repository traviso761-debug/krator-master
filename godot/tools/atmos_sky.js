// The shared sky's Godot side, from core/atmos itself (SKY-PLAN.md, step S0): ATMOS.skyGLSL() (core/atmos/sky/89-atmos-g-sky.js)
// translated to Godot shading language as godot/shaders/atmos_sky.gdshaderinc, which godot/shaders/sky.gdshader (a
// shader_type sky) includes; and the golden vectors godot/tests/sky/golden.json the GDScript twin (krator/sky_model.gd) is
// tested against: skyState at a spread of sites, hours and days (sun, giant, its axis and libration, the ring, all six
// moons), skyLook (the colour script), siteAt, skyDate, the bright stars and a digest of the noise volume.
//   node godot/tools/atmos_sky.js            writes both (rerun after changing core/atmos/sky or its presets)
//   node godot/tools/atmos_sky.js --print    prints the include instead
// The chunk is GLSL ES 3 already close to Godot's language; the translation splits the comma lists of uniforms (Godot
// declares one a line), gives the samplers their hints and drops nothing else. Its uniforms stay ordinary material
// uniforms (krator/sky.gd sets them on the Sky's ShaderMaterial), not globals: one sky per world.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..', '..'), ATM = path.join(ROOT, 'core', 'atmos');
const OUT = path.join(__dirname, '..', 'shaders', 'atmos_sky.gdshaderinc');
const GOLD = path.join(__dirname, '..', 'tests', 'sky', 'golden.json');
const DATA = path.join(__dirname, '..', 'data', 'sky');   // what krator/sky.gd reads: the constants and presets, the noise volume

function load() {
  const files = ['89-atmos-0-core.js', '89-atmos-0p-presets.js'].map(f => path.join(ATM, f))
    .concat(fs.readdirSync(path.join(ATM, 'sky')).filter(f => /^89-atmos-.*\.js$/.test(f)).sort().map(f => path.join(ATM, 'sky', f)));
  global.window = global;
  eval(files.map(f => fs.readFileSync(f, 'utf8')).join('\n') + ';global.ATMOS=ATMOS;');
  return global.ATMOS;
}

const HINTS = { uNoise: 'repeat_enable, filter_linear', uRidgeTex: 'filter_nearest', uMoonMaps: 'repeat_enable, filter_linear_mipmap' };

function gdshaderinc(A) {
  const lines = A.skyGLSL().split('\n'), out = [];
  for (const ln of lines) {
    // a line of uniform declarations, possibly several statements: 'uniform vec3 a,b[4];uniform float c;'
    if (/^\s*'?uniform /.test(ln) || /^uniform /.test(ln)) {
      for (const st of ln.split(';').map(s => s.trim()).filter(Boolean)) {
        const m = st.match(/^uniform\s+(?:highp\s+|mediump\s+|lowp\s+)?(\w+)\s+(.+)$/);
        if (!m) throw new Error('cannot read the uniform line: ' + st);
        for (const name of m[2].split(',').map(s => s.trim())) {
          const base = name.replace(/\[.*$/, '');
          out.push('uniform ' + m[1] + ' ' + name + (HINTS[base] ? ' : ' + HINTS[base] : '') + ';');
        }
      }
    } else out.push(ln);
  }
  const body = out.join('\n');
  for (const bad of [/\bprecision\b/, /\bgl_\w+/, /#include/, /\bhighp\b/, /\btexture2D\b/])
    if (bad.test(body)) throw new Error('untranslated GLSL in the sky chunk: ' + bad);
  return ['// GENERATED by godot/tools/atmos_sky.js from core/atmos/sky/89-atmos-g-sky.js (ATMOS.skyGLSL()).',
    '// Do not edit: rerun   node godot/tools/atmos_sky.js   after changing core/atmos/sky. core/atmos/SKY-PLAN.md, section 4.',
    '// vec3 atmSky(vec3 d): the sky\'s display colour toward world direction d, every layer composited back to front (deep',
    '// sky, sun, moons, giant, ring, air, clouds, ridges). Its uniforms are set each frame by krator/sky.gd from the sky model',
    '// (krator/sky_model.gd, the twin of 89-atmos-e-skymodel.js and 89-atmos-f-skypresets.js).',
    '#ifndef ATMOS_SKY_INC', '#define ATMOS_SKY_INC', body, '#endif', ''].join('\n');
}

const r = (v, n) => Array.isArray(v) ? v.map(x => r(x, n)) : (typeof v === 'number' ? +v.toFixed(n == null ? 12 : n) : v);

function golden(A) {
  const S = A.SKY, sites = [A.siteAt(446, 690), A.siteAt(755, 351), A.siteAt(450, 1040), A.siteAt(814, 189)];
  const state = [];
  for (const site of sites) for (const [h, d] of [[6, 0], [12, 0], [19.5, 3], [0, -88], [23.25, 91], [9.4, 140.6]]) {
    const s = A.skyState(site, h, d);
    state.push({ px: site.px, py: site.py, hour: h, day: d, latitude: site.latitude, subGiantLon: site.subGiantLon,
      sunDir: s.sunDir, giantDir: s.giantDir, giantAxis: s.giantAxis, pole: s.pole, ringOpen: s.ringOpen, ringLine: s.ringLine,
      ringNormal: A.skyRingNormal(s), eclipse: s.eclipse, giantLit: s.giantLit, spin: s.spin, lst: s.lst, clusterDir: s.clusterDir,
      eq: s.eq, moons: s.moons.map(m => ({ name: m.name, dir: m.dir, light: m.light, lead: m.lead, toGiant: m.toGiant,
        radiusDeg: m.radiusDeg, distKm: m.distKm, lit: m.lit, front: m.front })),
      station: { dir: s.station.dir, dist: s.station.dist, axis: s.station.axis, vel: s.station.vel, radiusDeg: s.station.radiusDeg, lit: s.station.lit, up: s.station.up } });
  }
  const P = A.skyPreset('standard', { site: { px: 446, py: 690 } }), look = [];
  for (const [h, d, w] of [[6, 0, null], [12, 0, null], [19.2, 0, null], [0, -88, null], [14, 30, { cover: .45, grey: .8 }], [10, 5, { fog: 1, grey: .4 }]]) {
    const s = A.skyState(A.siteAt(446, 690), h, d), L = A.skyLook(P, s, w);
    look.push({ hour: h, day: d, weather: w, sunAlt: s.sunAlt, eclipse: s.eclipse, giantLit: s.giantLit, look: L });
  }
  const dates = [[0, 6], [-1, 12], [91, 12], [-200, 3], [365, 0]].map(([d, h]) => ({ day: d, hour: h, date: A.skyDate(d, h) }));
  const vol = A.skyNoiseVolume(64);
  return r({ sky: S, preset: P, state, look, dates, stars: S.stars,
    noise: { n: 64, sha1: crypto.createHash('sha1').update(Buffer.from(vol)).digest('hex'), sample: Array.from(vol.slice(0, 64)),
      n8: Array.from(A.skyNoiseVolume(8)) },
    gdshaderinc_sha1: crypto.createHash('sha1').update(gdshaderinc(A)).digest('hex') });
}

// the cloud shade (SKY-PLAN.md 11.1) for Godot's ground and plant shaders: the same chunk, its uniforms renamed to global
// shader parameters (project.godot) that krator/sky.gd sets each frame. In a spatial shader's light():
//   ATTENUATION *= atmCloudShade((INV_VIEW_MATRIX * vec4(VERTEX, 1.0)).xyz, normalize((INV_VIEW_MATRIX * vec4(LIGHT, 0.0)).xyz));
// and the wet: ALBEDO *= 1.0 - 0.38 * atm_wet * porosity; ROUGHNESS *= 1.0 - 0.55 * atm_wet (fragment()).
const CS_GLOBALS = { uNoise: 'atm_sky_noise', uCloud: 'atm_cloud', uCloudH: 'atm_cloud_h', uWind: 'atm_cloud_wind', uTime: 'atm_time', uWet: 'atm_wet' };
function cloudshadeinc(A) {
  let body = A.cloudShadeGLSL().split('\n').filter(l => !/^uniform /.test(l)).join('\n');
  for (const [k, v] of Object.entries(CS_GLOBALS)) body = body.replace(new RegExp('\\b' + k + '\\b', 'g'), v);
  const types = { atm_sky_noise: 'sampler3D', atm_cloud: 'vec4', atm_cloud_h: 'vec4', atm_cloud_wind: 'vec2', atm_time: 'float', atm_wet: 'float' };
  return ['// GENERATED by godot/tools/atmos_sky.js from core/atmos/sky/89-atmos-g-sky.js (ATMOS.cloudShadeGLSL()). Do not edit.',
    "// float atmCloudShade(vec3 worldPos, vec3 worldLightDir): the sky's clouds shading a ground or plant point (1 in the open).",
    '#ifndef ATMOS_CLOUDSHADE_INC', '#define ATMOS_CLOUDSHADE_INC']
    .concat(Object.values(CS_GLOBALS).map(v => 'global uniform ' + types[v] + ' ' + v + (v === 'atm_sky_noise' ? ' : repeat_enable, filter_linear' : '') + ';'), [body, '#endif', '']).join('\n');
}

module.exports = { load, gdshaderinc, golden, cloudshadeinc };

if (require.main === module) {
  const A = load(), s = gdshaderinc(A);
  if (process.argv.includes('--print')) { process.stdout.write(s); return; }
  fs.writeFileSync(OUT, s); console.log('wrote godot/shaders/atmos_sky.gdshaderinc:', s.length, 'bytes');
  fs.writeFileSync(path.join(path.dirname(OUT), 'atmos_cloudshade.gdshaderinc'), cloudshadeinc(A)); console.log('wrote godot/shaders/atmos_cloudshade.gdshaderinc');
  fs.mkdirSync(path.dirname(GOLD), { recursive: true });
  fs.writeFileSync(GOLD, JSON.stringify(golden(A), null, 0) + '\n'); console.log('wrote godot/tests/sky/golden.json');
  fs.mkdirSync(DATA, { recursive: true });
  fs.writeFileSync(path.join(DATA, 'sky.json'), JSON.stringify({ sky: A.SKY, presets: A.PRESETS.sky, maxRidges: A.SKY_MAX_RIDGES }, null, 1) + '\n');
  fs.writeFileSync(path.join(DATA, 'noise64.bin'), Buffer.from(A.skyNoiseVolume(64)));
  console.log('wrote godot/data/sky/sky.json and noise64.bin');
}
