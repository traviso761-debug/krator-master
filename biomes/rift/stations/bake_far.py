#!/usr/bin/env python3
"""Bake the scale model's ground round a Rift station into its far-field data fragment (PLAN-STATIONS.md, section 6: KFAR).

    python3 tools/scale-model/extract_region.py <scale model page> <regions> <settlements> "rift" <cut dir>
    python3 biomes/rift/stations/bake_far.py <cut dir> <station> <px> <py> <y0> [--radius 14]

<cut dir>   an extract_region.py cut of the `rift` polygon (elev.png, region.json)
<station>   the station's folder name under biomes/rift/stations/ (the fragment is written there as 44f-host-far-data.js)
<px> <py>   the station's centre on the model's full grid (2 km a pixel): the page's origin
<y0>        the model's height at the page's y = 0 (metres)
--radius    the half-size of the window, in the model's height cells (4 km each; 14: 56 km round)

It writes the model's heights (half-resolution cells, relative to y0, metres) and its water levels (relative, or null where dry) on
the cells' own grid, with each cell's page position: FAR_MODEL = {cell, x0, z0, n, h, w}. The page draws them with core/terrain's
KFAR (89f-host-far.js) beyond its ground square. Deterministic: no randomness.
"""
import argparse, json, os
import numpy as np
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument('cut'); ap.add_argument('station'); ap.add_argument('px', type=float); ap.add_argument('py', type=float)
ap.add_argument('y0', type=float); ap.add_argument('--radius', type=int, default=14)
a = ap.parse_args()
R = json.load(open(os.path.join(a.cut, 'region.json'), encoding='utf-8'))
H = R['heights']; lo, hi = H['lo'], H['hi']; i0, j0 = H['origin_cell']; su, sv = H['su'], H['sv']
e = np.array(Image.open(os.path.join(a.cut, 'elev.png')))
E = lo + ((e[..., 0].astype(np.int64) << 8) | e[..., 1]) / 65535 * (hi - lo)
w = np.array(Image.open(os.path.join(a.cut, 'wlev.png')))
WH = w[..., 2] > 127
WL = lo + ((w[..., 0].astype(np.int64) << 8) | w[..., 1]) / 65535 * (hi - lo)
ci, cj = int(round(a.px * su - i0)), int(round(a.py * sv - j0))
n = 2 * a.radius + 1
hs, ws = [], []
for j in range(cj - a.radius, cj + a.radius + 1):
    for i in range(ci - a.radius, ci + a.radius + 1):
        ii, jj = min(max(i, 0), E.shape[1] - 1), min(max(j, 0), E.shape[0] - 1)
        hs.append(int(round(E[jj, ii] - a.y0)))
        ws.append(int(round(WL[jj, ii] - a.y0)) if WH[jj, ii] else None)
# the page position of cell (ci - radius, cj - radius): full px ((i + i0) / su, (j + j0) / sv), 2 km a pixel from the centre
x0 = ((ci - a.radius + i0) / su - a.px) * 2000.0
z0 = ((cj - a.radius + j0) / sv - a.py) * 2000.0
cell = 2000.0 / su
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), a.station, '44f-host-far-data.js')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// ================================================================= HOST — the far field\'s data: the scale model round the station\n')
    f.write('// GENERATED by biomes/rift/stations/bake_far.py from %s (px %g,%g, y 0 at %g m): do not edit; rerun it.\n'
            % (R.get('source', 'the scale model'), a.px, a.py, a.y0))
    f.write('// h: the model\'s heights relative to y 0 (m), row by row (z outer), its own %d m cells; w: the water level there, or null.\n' % round(cell))
    f.write('const FAR_MODEL=%s;\n' % json.dumps({'cell': round(cell, 3), 'x0': round(x0, 1), 'z0': round(z0, 1), 'n': n, 'h': hs, 'w': ws}, separators=(',', ':')))
print('wrote', out, n, 'x', n, 'cells of', round(cell), 'm; origin', round(x0), round(z0))
