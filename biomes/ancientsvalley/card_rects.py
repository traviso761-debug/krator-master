"""The valley's card boxes: where each of a nine-plant sheet's plants really lies (writes src/41e-av-cardrects.js).

The crop and creeper cards are generated sheets of nine plants on a rough 3 x 3 grid, not an exact one: a plant reaches past its third of the
sheet, so cutting a card at the thirds (BIO.geo.cells' even grid) slices a straight edge through its leaves (the owner, 2026-11-10: "the herbs
still have a straight boundary cutting off part of the leaf card"). For each cell this finds the plant whose body lies in it: the opaque texels
(alpha >= 107, the cut) inside the cell grown by 0.4 of a cell each way, their connected pieces whose centre falls in the cell itself, and the box
round those pieces, padded by half a percent. A cell with nothing found keeps its third. The boxes are in the library's convention (u across,
v down the sheet, as BIO.geo.cells' o.rects). Read from the packed textures the pages sample.

  python biomes/ancientsvalley/card_rects.py      (after a pack changes; commit the fragment)
"""
import glob, io, json, os
import numpy as np
from PIL import Image
from scipy import ndimage

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SOURCES = sorted(glob.glob(os.path.join(ROOT, 'kits', 'crops', 'tex', 'card_crop*.albedo.webp'))
                 + glob.glob(os.path.join(ROOT, 'kits', 'crops', 'tex', 'card_orchard*.albedo.webp'))
                 + glob.glob(os.path.join(ROOT, 'kits', 'crops', 'tex', 'card_croptree*.albedo.webp'))
                 + [os.path.join(HERE, 'tex', 'creeper.albedo.webp'), os.path.join(HERE, 'tex', 'mosshang.albedo.webp')])
N, CUT, GROW, PAD, RES, MINPX = 3, 107, 0.4, 0.005, 384, 12


def rects(path):
    im = Image.open(path)
    if 'A' not in im.mode:
        return None
    a = np.asarray(im.getchannel('A').resize((RES, RES), Image.BILINEAR)) >= CUT
    out = []
    c = RES / N
    for k in range(N * N):
        cx, cy = k % N, k // N
        x0, y0 = int(max(0, (cx - GROW) * c)), int(max(0, (cy - GROW) * c))
        x1, y1 = int(min(RES, (cx + 1 + GROW) * c)), int(min(RES, (cy + 1 + GROW) * c))
        win = a[y0:y1, x0:x1]
        lab, n = ndimage.label(win)
        keep = np.zeros_like(win)
        for i in range(1, n + 1):
            ys, xs = np.nonzero(lab == i)
            if len(xs) < MINPX:
                continue
            mx, my = (xs.mean() + x0) / c, (ys.mean() + y0) / c
            if cx <= mx < cx + 1 and cy <= my < cy + 1:
                keep |= lab == i
        ys, xs = np.nonzero(keep)
        if not len(xs):
            out.append([round(cx / N, 4), round(cy / N, 4), round((cx + 1) / N, 4), round((cy + 1) / N, 4)])
            continue
        u0, v0 = max(0, (xs.min() + x0) / RES - PAD), max(0, (ys.min() + y0) / RES - PAD)
        u1, v1 = min(1, (xs.max() + 1 + x0) / RES + PAD), min(1, (ys.max() + 1 + y0) / RES + PAD)
        out.append([round(u0, 4), round(v0, 4), round(u1, 4), round(v1, 4)])
    return out


def main():
    table = {}
    for p in SOURCES:
        if not os.path.isfile(p):
            continue
        name = os.path.basename(p).replace('.albedo.webp', '')
        r = rects(p)
        if r:
            table[name] = r
    body = json.dumps(table, separators=(',', ':')).replace('],"', '],\n "')
    js = ('// ================================================================= THE CARD BOXES: where each of a nine-plant sheet\'s plants lies\n'
          '// [G data] Generated by biomes/ancientsvalley/card_rects.py from the packed textures (do not edit by hand): for each card family, nine boxes\n'
          '// [u0, v0, u1, v1] in the library\'s convention (v down the sheet), one per cell of the rough 3 x 3 grid, each round its plant (BIO.geo.cells\'\n'
          '// o.rects), so a quad shows one whole plant and never a straight cut through its leaves (the owner, 2026-11-10).\n'
          '//   AV.CARD_RECTS[family] -> [[u0, v0, u1, v1] x 9] | undefined\n'
          'AV.CARD_RECTS=' + body + ';\n')
    io.open(os.path.join(HERE, 'src', '41e-av-cardrects.js'), 'w', encoding='utf-8', newline='\n').write(js)
    print('wrote src/41e-av-cardrects.js: %d sheets' % len(table))


if __name__ == '__main__':
    main()
