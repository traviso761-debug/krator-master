#!/usr/bin/env python3
"""The scale model (5.1) round one station, as a page fragment (FB_MODEL), read at build time.

    fragment(px, py, key) -> the JavaScript text of the generated fragment
    window(px, py)        -> the same as a dict (for survey printing)

The page stands on the model's own ground: a window of the 5.1 height grid (2 km cells, 22 x 22 round the station: the far
field reads it to 14 km) with each cell's water level, and the station's climate read off the nearest land cells (the
model keeps no climate on its water cells). The decoding is tools/scale-model/smodel/page.py's (heights 16 bits in R,G over
[lo, hi], B the water flag; tm, tw, tc one byte less 90 degC; p one byte of 4000 mm), done here so the build does not
import the model's page tools. Each raster is opened with open() so tools/build.py records it as an input: a rebake of the
model marks the pages stale. The page interpolates the heights with a cubic B-spline (45-host-stage.js): smooth, and it
never overshoots a crater's floor or a tarn's bed the way an interpolating cubic would.
"""
import io, json, math, os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DATA = os.path.join(ROOT, 'tools', 'scale-model', 'model', 'data')
HALF = 10                    # cells either side of the station's cell: 22 x 22 cells, +-20 km
_CACHE = {}


def _img(name, mode):
    from PIL import Image
    import numpy as np
    if name not in _CACHE:
        with open(os.path.join(DATA, name), 'rb') as fh:
            _CACHE[name] = np.array(Image.open(io.BytesIO(fh.read())).convert(mode))
    return _CACHE[name]


def _model():
    with open(os.path.join(DATA, 'model.json'), encoding='utf-8') as fh:
        keys = {o['key']: o for o in json.load(fh)['keys']}
    return keys['lo']['value'], keys['hi']['value']


def window(px, py):
    import numpy as np
    lo, hi = _model()
    dec = lambda a: lo + ((a[..., 0].astype(np.int64) << 8) | a[..., 1]) / 65535.0 * (hi - lo)
    h, wl = _img('h.png', 'RGB'), _img('wl.png', 'RGB')
    E, W = dec(h), dec(wl)
    whas = wl[..., 2] > 127
    tm, tw, tc = (_img(k + '.png', 'L').astype(float) - 90 for k in ('tm', 'tw', 'tc'))
    rain = _img('p.png', 'L').astype(float) / 255 * 4000
    cls = _img('c.png', 'L')
    with open(os.path.join(DATA, 'climate.json'), encoding='utf-8') as fh:
        C = json.load(fh)['classes']
    i0, j0 = int(math.floor(px)) - HALF, int(math.floor(py)) - HALF
    n = 2 * HALF + 2
    hs, ws, ks = [], [], []
    for j in range(j0, j0 + n):
        for i in range(i0, i0 + n):
            hs.append(round(float(E[j, i]), 1))
            ws.append(round(float(W[j, i]), 1) if whas[j, i] else None)
    # the climate: the mean of the land cells within two of the station's (the water cells carry none), and the classes round it
    cj, ci = int(round(py)), int(round(px))
    land = [(j, i) for j in range(cj - 2, cj + 3) for i in range(ci - 2, ci + 3) if tm[j, i] > -89 and not whas[j, i]]
    mean = lambda A: round(sum(float(A[j, i]) for j, i in land) / len(land), 1) if land else None
    seen = {}
    for j in range(cj - 3, cj + 4):
        for i in range(ci - 3, ci + 4):
            k = C[cls[j, i]]['code'] if cls[j, i] < len(C) else str(int(cls[j, i]))
            seen[k] = seen.get(k, 0) + 1
    koppen = sorted(seen, key=lambda k: -seen[k])
    # the range's five volcanoes (the model's vents.json, region 'Firebliss Range'): the plume's sources and the far field's cones
    with open(os.path.join(DATA, 'vents.json'), encoding='utf-8') as fh:
        V = json.load(fh)
    V = V if isinstance(V, list) else V.get('vents', [])
    vents = [{'name': v['name'], 'px': v['px'], 'peak': v.get('peak'), 'floor': v.get('floor'), 'radius': v.get('radius')} for v in V if v.get('region') == 'Firebliss Range']
    return {'px': px, 'py': py, 'cell': 2000, 'i0': i0, 'j0': j0, 'n': n, 'h': hs, 'wl': ws, 'vents': vents,
            'clim': {'tm': mean(tm), 'tw': mean(tw), 'tc': mean(tc), 'rain': round(mean(rain) or 0), 'koppen': koppen}}


def fragment(px, py, key):
    M = window(px, py)
    return ('// ==================== 44m-host-model.js (generated by build.py from tools/scale-model/model/data: do not edit)\n'
            '// the scale model 5.1 round the station (' + key + ', 5.1 px ' + str(px) + ',' + str(py) + '): heights and water levels on the\n'
            '// model\'s 2 km cells, row by row from (i0, j0); the climate off the nearest land cells (model_site.py)\n'
            'const FB_MODEL=' + json.dumps(M, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    import sys
    px, py = float(sys.argv[1]), float(sys.argv[2])
    M = window(px, py)
    print(json.dumps(M['clim']))
    # a survey map: the B-spline ground every 300 m over +-3 km, '~' under the nearest water cell's level
    n, i0, j0 = M['n'], M['i0'], M['j0']
    H = lambda i, j: M['h'][max(0, min(n - 1, j)) * n + max(0, min(n - 1, i))]
    def B(t):
        return [(1 - t) ** 3 / 6, (3 * t ** 3 - 6 * t * t + 4) / 6, (-3 * t ** 3 + 3 * t * t + 3 * t + 1) / 6, t ** 3 / 6]
    def h(x, z):
        u, v = px + x / 2000 - i0, py + z / 2000 - j0
        i, j = int(math.floor(u)), int(math.floor(v))
        bu, bv = B(u - i), B(v - j)
        return sum(bu[a] * bv[b] * H(i - 1 + a, j - 1 + b) for a in range(4) for b in range(4))
    lv = [w for w in M['wl'] if w is not None]
    L = max(lv) if lv else -1e9
    print('water level %.1f' % L)
    for z in range(-3000, 3001, 300):
        print(' '.join(('~~~~' if h(x, z) < L else '%4d' % (h(x, z) - (L if L > 0 else 0))) for x in range(-3000, 3001, 300)))
