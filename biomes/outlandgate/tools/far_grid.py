#!/usr/bin/env python3
"""The far field's heights from the scale model (5.1), written as a [G data] fragment the station's stage reads (PLAN.md section 7).

    python3 biomes/outlandgate/tools/far_grid.py            # writes src/44f-og-far-data.js (station 1, the Narrows: 5.1 px 1438,326)

A square of the model's height grid (2 km cells) centred on the station's pixel, out to +-R px, as integer metres, row by row from
north (low y) to south. The page maps px to metres: x = (px - cx) * 2000 east, z = (py - cy) * 2000 south. Rerun after a model edit.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'scale-model'))
from smodel import page  # noqa: E402

def grid(cx, cy, r):
    D = page.load()
    E, water = page.heights(D)
    whas, wlev = page.water_levels(D)
    rows = []
    for py in range(cy - r, cy + r + 1):
        rows.append([int(round(float(E[py, px]))) for px in range(cx - r, cx + r + 1)])
    return rows

def main():
    cx, cy, r = 1438, 326, 40
    rows = grid(cx, cy, r)
    out = os.path.join(HERE, '..', 'src', '44f-og-far-data.js')
    body = ('// ================================================================= OUTLAND GATE — the far field\'s heights from the scale model\n'
            '// [G data] GENERATED by tools/far_grid.py from tools/scale-model/model/data (map 5.1): do not edit; rerun it after a model edit.\n'
            '// The model\'s height grid (2 km cells, metres) round station 1\'s pixel (5.1 px %d,%d), +-%d px, rows north to south: x = (px - %d) * 2000\n'
            '// east, z = (py - %d) * 2000 south. The stage reads it past the map (the walls: 4-5 km 48-54 km out, 10-14 km beyond).\n'
            'var OG_FAR={map:"5.1",cx:%d,cy:%d,r:%d,cell:2000,h:%s};\n') % (cx, cy, r, cx, cy, cx, cy, r, json.dumps(rows, separators=(',', ':')))
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(body)
    print('wrote', os.path.relpath(out, ROOT).replace(os.sep, '/'), '(%d x %d, %d KB)' % (len(rows), len(rows[0]), len(body) // 1024))

if __name__ == '__main__':
    main()
