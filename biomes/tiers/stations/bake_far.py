#!/usr/bin/env python3
"""Bake the scale model round a Tiers station into its data fragment (PLAN.md sections 1, 9 and 10a: the land and KFAR).
The Great Chasm's bake (biomes/greatchasm/stations/bake_far.py), with the model's lake cells and levels added.

    python3 biomes/tiers/stations/bake_far.py <station> <px> <py> [--radius 60]
    python3 biomes/tiers/stations/bake_far.py --all

<station>   the station's folder under biomes/tiers/stations/ (the fragment is written there as 44f-host-far-data.js)
<px> <py>   the station's centre on the 5.1 map (1821 x 1723, 2 km a pixel): the page's origin (may be fractional)
--radius    the half-size of the window in the model's cells (2 km each; 60: 120 km round: the stair to the crown and the Outer Wall)

It reads tools/scale-model/model/data (smodel.page: the build's own source, the same numbers the plan's survey read) and writes the model's
heights (metres above the datum: the page's y is the model's height, no offset) on the cells' own grid, each cell's climate class (one
letter a cell, KEY below), each cell's water (one letter: '.' dry, 'w' a lake or sea cell under its level) and the levels of the water
bodies it holds (wl: metres, per water cell, '' elsewhere, as a list keyed by cell index), and the site's numbers. The page's x runs east
and z south, 2,000 m a pixel; the cell (i, j) of the window sits at x = (i - radius + (round(px) - px)) * 2000 from the site, so a
fractional site keeps the cells on the model's own pixels. Deterministic: no randomness.
"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'scale-model'))
from smodel import page  # noqa: E402

# station 1, the Lake of the Tiers: centred on the drawn north shore (PLAN.md 10a: the pin 1262,512 stands 4 km from the water)
SITES = {'lake': (1262, 513.4)}
CODES = ['Af', 'Am', 'Aw', 'BWh', 'BWk', 'BSh', 'BSk', 'Csa', 'Csb', 'Csc', 'Cwa', 'Cwb', 'Cwc', 'Cfa', 'Cfb', 'Cfc', 'Dsa', 'Dsb', 'Dsc', 'Dwa',
         'Dwb', 'Dwc', 'Dfa', 'Dfb', 'Dfc', 'Dfd', 'ET', 'EF', 'XA', 'XV', 'XS', 'XW', 'HT', 'HF', 'O', 'WS', 'WX', 'WH']
KEY = {c: 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOP'[i] for i, c in enumerate(CODES)}


def bake(D, E, C, codes, T, P, W, name, px, py, radius):
    has, lev = W
    n = 2 * radius + 1
    ix, iy = int(round(px)), int(round(py))
    hs, cs, ws, wl = [], [], [], {}
    for j in range(n):
        for i in range(n):
            x = min(max(ix + i - radius, 0), E.shape[1] - 1)
            y = min(max(iy + j - radius, 0), E.shape[0] - 1)
            hs.append(int(round(float(E[y, x]))))
            c = int(C[y, x]); code = codes[c] if c < len(codes) else '?'
            cs.append(KEY.get(code, '?'))
            w = bool(has[y, x]) and float(lev[y, x]) > float(E[y, x]) - 5
            ws.append('w' if w else '.')
            if w: wl[j * n + i] = int(round(float(lev[y, x])))
    site = {'px': px, 'py': py, 'cx': ix, 'cy': iy, 'off': [round((ix - px) * 2000, 1), round((iy - py) * 2000, 1)], 'h': hs[radius * n + radius],
            'cls': codes[int(C[iy, ix])], 'tm': float(T['tm'][iy, ix]), 'tw': float(T['tw'][iy, ix]), 'tc': float(T['tc'][iy, ix]),
            'rain': round(float(P[iy, ix])), 'sky': [round(px - 272, 1), round(py - 330, 1)]}
    rec = {'cell': 2000, 'n': n, 'r': radius, 'site': site, 'h': hs, 'c': ''.join(cs), 'w': ''.join(ws), 'wl': wl,
           'key': {v: k for k, v in KEY.items()}}
    body = ('// ================================================================= HOST — the far field\'s data: the scale model round the station\n'
            '// GENERATED by biomes/tiers/stations/bake_far.py from the scale model 5.1 (tools/scale-model/model/data; px %s,%s): do not\n'
            '// edit; rerun it. h: the model\'s heights (m, the page\'s y), row by row (z outer) on its own 2 km cells, the site\'s pixel at the\n'
            '// middle cell (r, r), offset site.off m from the page\'s origin; c: each cell\'s climate class, one letter (key); w: \'w\' a water\n'
            '// cell under its level, wl its level by cell index; site: the model\'s numbers at the station\'s pixel.\n'
            'const FAR_MODEL=%s;\n') % (px, py, json.dumps(rec, separators=(',', ':')))
    out = os.path.join(HERE, name, '44f-host-far-data.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(body)
    print('wrote %s (%d cells, %d water, %d KB; the site %d m, %s)' % (os.path.relpath(out, ROOT).replace(os.sep, '/'), n * n, len(wl), len(body) // 1024,
                                                                         site['h'], site['cls']))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('station', nargs='?'); ap.add_argument('px', nargs='?', type=float); ap.add_argument('py', nargs='?', type=float)
    ap.add_argument('--radius', type=int, default=60); ap.add_argument('--all', action='store_true')
    a = ap.parse_args()
    D = page.load()
    E, _ = page.heights(D)
    if E.shape != (D['fullH'], D['fullW']):
        sys.exit('bake_far.py: the height grid is not the full map grid (%s); this script reads one cell a pixel' % (E.shape,))
    C = page.raster(D, 'c')[..., 0]
    codes = [c['code'] for c in D['climate']['classes']]
    if codes != CODES:
        sys.exit('bake_far.py: the model\'s climate classes changed; update CODES')
    T = {k: page.raster(D, k)[..., 0].astype(float) - 90 for k in ('tm', 'tw', 'tc')}
    P = page.raster(D, 'p')[..., 0].astype(float) / 255 * 4000
    W = page.water_levels(D)
    jobs = [(s, xy[0], xy[1]) for s, xy in SITES.items()] if a.all else [(a.station, a.px, a.py)]
    for name, px, py in jobs:
        if name is None or px is None:
            sys.exit('bake_far.py: give <station> <px> <py>, or --all')
        bake(D, E, C, codes, T, P, W, name, px, py, a.radius)


if __name__ == '__main__':
    main()
