#!/usr/bin/env python3
"""Bake the scale model round a Great Chasm station into its data fragment (PLAN.md sections 7 and 8: the land and KFAR).

    python3 biomes/greatchasm/stations/bake_far.py <station> <px> <py> [--radius 60]
    python3 biomes/greatchasm/stations/bake_far.py --all

<station>   the station's folder under biomes/greatchasm/stations/ (the fragment is written there as 44f-host-far-data.js)
<px> <py>   the station's centre on the 5.1 map (1821 x 1723, 2 km a pixel): the page's origin
--radius    the half-size of the window in the model's cells (2 km each; 60: 120 km round, the chasm's far walls)

It reads tools/scale-model/model/data (smodel.page: the build's own source, the same numbers the plan's survey read) and writes the model's
heights (metres above the datum: the page's y is the model's height, no offset) on the cells' own grid, each cell's climate class (one
letter a cell, KEY below), and the site's numbers. The page's x runs east and z south, 2,000 m a pixel; the cell (i, j) of the window sits
at x = (i - radius) * 2000, z = (j - radius) * 2000 from the site's pixel (which may be fractional). Deterministic: no randomness.
"""
import argparse, json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'scale-model'))
from smodel import page  # noqa: E402

SITES = {'sill': (1697, 1028), 'bench': (1718, 924), 'deep': (1692, 895), 'headwall': (1664, 812), 'eastrim': (1726, 888)}
KEY = {'XW': 'x', 'BWk': 'b', 'BSk': 's', 'ET': 't', 'EF': 'f', 'HT': 'h', 'HF': 'g', 'O': 'o'}


def bake(D, E, C, codes, T, P, name, px, py, radius, out_dir=None, by='biomes/greatchasm/stations/bake_far.py'):
    n = 2 * radius + 1
    hs, cs = [], []
    for j in range(n):
        for i in range(n):
            x = min(max(int(round(px + i - radius)), 0), E.shape[1] - 1)
            y = min(max(int(round(py + j - radius)), 0), E.shape[0] - 1)
            hs.append(int(round(float(E[y, x]))))
            c = int(C[y, x]); code = codes[c] if c < len(codes) else '?'
            cs.append(KEY.get(code, '?'))
    ix, iy = int(round(px)), int(round(py))
    site = {'px': px, 'py': py, 'h': hs[radius * n + radius], 'cls': codes[int(C[iy, ix])], 'tm': float(T['tm'][iy, ix]),
            'tw': float(T['tw'][iy, ix]), 'tc': float(T['tc'][iy, ix]), 'rain': round(float(P[iy, ix])), 'sky': [px - 272, py - 330]}
    rec = {'cell': 2000, 'n': n, 'r': radius, 'site': site, 'h': hs, 'c': ''.join(cs), 'key': {v: k for k, v in KEY.items()}}
    body = ('// ================================================================= HOST — the far field\'s data: the scale model round the station\n'
            '// GENERATED by %s from the scale model 5.1 (tools/scale-model/model/data; px %s,%s): do not\n'
            '// edit; rerun it. h: the model\'s heights (m, the page\'s y), row by row (z outer) on its own 2 km cells, the site\'s pixel at the\n'
            '// middle cell (r, r); c: each cell\'s climate class, one letter (key); site: the model\'s numbers at the station\'s pixel.\n'
            'const FAR_MODEL=%s;\n') % (by, px, py, json.dumps(rec, separators=(',', ':')))
    out = os.path.join(out_dir or HERE, name, '44f-host-far-data.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(body)
    print('wrote %s (%d cells, %d KB; the site %d m, %s)' % (os.path.relpath(out, ROOT).replace(os.sep, '/'), n * n, len(body) // 1024, site['h'], site['cls']))


def load():
    """the model's rasters the bake reads: (D, E, C, codes, T, P)"""
    D = page.load()
    E, _ = page.heights(D)
    if E.shape != (D['fullH'], D['fullW']):
        sys.exit('bake_far.py: the height grid is not the full map grid (%s); this script reads one cell a pixel' % (E.shape,))
    C = page.raster(D, 'c')[..., 0]
    codes = [c['code'] for c in D['climate']['classes']]
    T = {k: page.raster(D, k)[..., 0].astype(float) - 90 for k in ('tm', 'tw', 'tc')}
    P = page.raster(D, 'p')[..., 0].astype(float) / 255 * 4000
    return D, E, C, codes, T, P


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('station', nargs='?'); ap.add_argument('px', nargs='?', type=float); ap.add_argument('py', nargs='?', type=float)
    ap.add_argument('--radius', type=int, default=60); ap.add_argument('--all', action='store_true')
    a = ap.parse_args()
    D, E, C, codes, T, P = load()
    jobs = [(s, xy[0], xy[1]) for s, xy in SITES.items()] if a.all else [(a.station, a.px, a.py)]
    for name, px, py in jobs:
        if name is None or px is None:
            sys.exit('bake_far.py: give <station> <px> <py>, or --all')
        bake(D, E, C, codes, T, P, name, px, py, a.radius)


if __name__ == '__main__':
    main()
